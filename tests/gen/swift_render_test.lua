-- The Swift skeleton renderer (tools/gen/swift_render.lua): the model of our own fixture dump (tests/gen/input/fixtures/swift) is
-- rendered and held to its golden text, so a renderer change that drops a modifier, a body, the spelling fix for a builtin, the
-- raw-enum rule, an external type's extension, the override, required, convenience or actor keyword, the public access of a final
-- class or the skipped opaque typealias turns the test red (the mutants: a member rendered without its access level, a protocol
-- requirement with a body, `Swift.Any` left as it is, the raw enum's synthesized `rawValue` declared again, an extension of another
-- module's type rendered as a declaration). The fixture is our own JSON in the digester's shape, not an Apple dump, and the test
-- reads no .swiftinterface. Run: xmake l tests/gen/swift_render_test.lua

local TOOLS = path.join(os.scriptdir(), "..", "..", "tools")
local json = import("core.base.json")

-- The golden text of the fixture module. Built by hand from the fixture, once, so the test shows what every rule produces.
local GOLDEN = [[// GENERATED by tools/gen.lua swiftcode. Do not edit.
// The Swift skeleton of Fixture, rendered from the declaration model.
import Foundation
import _Concurrency

public var limit: Swift.Int { fatalError("limit") }

public typealias Handle = Swift.Int

@available(iOS 13.0, *)
public struct Point: Swift.Equatable, Swift.Sendable {
    public var x: Swift.Int { fatalError("Point.x") }
    public var y: Key.Value { fatalError("Point.y") }
    public func moved(dx: Swift.Int) async throws -> Fixture.Point { fatalError("Point.moved(dx:)") }
}

public class Base {
    public func describe() -> Swift.String { fatalError("Base.describe()") }
    public required init() { fatalError("Base.init()") }
}

public final class Box: Fixture.Base, Swift.Sendable {
    public init(value: Swift.Int) throws { fatalError("Box.init(value:)") }
    public override func describe() -> Swift.String { fatalError("Box.describe()") }
    public convenience init() { fatalError("Box.init()") }
}

public actor Worker {
}

public enum Direction: Swift.Int, Swift.Hashable {
    case north
}

public protocol Renderer: Swift.Sendable {
    associatedtype Output
    func render(_ p0: Any) -> Any
}

extension Foundation.URL {
    public var tag: Swift.String { fatalError("URL.tag") }
}
]]

function main()
    local model = import("gen.swift_model", {rootdir = TOOLS, anonymous = true})
    local render = import("gen.swift_render", {rootdir = TOOLS, anonymous = true})
    local swift_shard = import("gen.swift_shard", {rootdir = TOOLS, anonymous = true})
    local failures = 0
    local function check(ok, label)
        if not ok then
            failures = failures + 1
            print("FAIL " .. label)
        end
    end

    local text = io.open(path.join(os.scriptdir(), "input", "fixtures", "swift", "model.json"), "rb"):read("a")
    local root = json.decode(text).ABIRoot
    local rows = assert(model.rows(root, "Fixture"))
    -- async has no key in the dump; the demangler is injected, so the test needs no toolchain (the line the real one prints for
    -- moved carries " async").
    model.annotate_async(rows, function(names)
        local out = {}
        for _, name in ipairs(names) do
            if name == "$s7Fixture5PointV5moved2dxACSi_tKF" then
                table.insert(out, name .. " ---> Fixture.Point.moved(dx: Swift.Int) async throws -> Fixture.Point")
            else
                table.insert(out, name .. " ---> Fixture.other")
            end
        end
        return out
    end)
    -- The SDK's Swift modules, as the command passes them: a qualifier outside this set is no module (Key is a generic parameter).
    local known = {Foundation = true, _Concurrency = true}
    local code, rendered = render.render(rows, "Fixture", known)

    check(code == GOLDEN, "the rendered fixture is the golden text")
    -- the keys of the declared rows, by the key the shard index and scope use: a type and one of its members
    check(rendered[swift_shard.key_of({kind = "swift-struct", container = "-", name = "Point"})] == true,
          "a declared type is among the rendered keys")
    check(rendered[swift_shard.key_of({kind = "swift-property", container = "Point", name = "x"})] == true,
          "a declared member is among the rendered keys")
    check(string.find(code, "import Key", 1, true) == nil, "a qualifier that is no SDK module is not imported")
    check(string.find(code, "public var limit: Swift.Int { fatalError(\"limit\") }", 1, true) ~= nil,
          "a module-level constant is a computed variable, not an enum case")

    -- The rules the golden holds, each named so a failure points at the rule and not only at a byte offset.
    check(string.find(code, "    public var x: Swift.Int { fatalError(\"Point.x\") }", 1, true) ~= nil,
          "a stored value is rendered as a computed property whose getter traps")
    check(string.find(code, "public func moved(dx: Swift.Int) async throws -> Fixture.Point", 1, true) ~= nil,
          "a method carries its parameter label, async and throws")
    check(string.find(code, "Swift.Any", 1, true) == nil, "a builtin is spelled without its Swift. prefix")
    check(string.find(code, "func render(_ p0: Any) -> Any\n", 1, true) ~= nil,
          "a protocol requirement has a signature and no body")
    check(string.find(code, "rawValue", 1, true) == nil, "a raw-value enum's synthesized rawValue is not declared again")
    -- A raw-value enum's synthesized members (not in the fixture): the raw type provides them, so the skeleton does not declare them and
    -- their keys are rendered keys (scope states them as generated stubs). The enum keeps its case and its raw type.
    local function raw_row(kind, name, container, extra)
        local row = {framework = "Fixture", kind = kind, name = name, container = container, side = "-", type = "-", params = "-",
                     accessors = "-", overriding = "-", availability = "-", owner_module = "-", attributes = "-", generic_sig = "-",
                     throwing = "-", async = "-", mutating = "-", init_kind = "-", is_open = "-", conformances = "-", superclass = "-",
                     raw = "-", usr = kind .. name}
        for key, value in pairs(extra or {}) do
            row[key] = value
        end
        return row
    end
    local level = raw_row("swift-enum", "Level", "-", {raw = "Int32", conformances = "RawRepresentable"})
    local low = raw_row("swift-constant", "low", "Level")
    local init_row = raw_row("swift-method", "init(rawValue:)", "Level", {params = "Swift.Int32"})
    local raw_value = raw_row("swift-property", "rawValue", "Level", {type = "Swift.Int32"})
    local raw_code, raw_keys = render.render({level, low, init_row, raw_value}, "Fixture", known)
    check(string.find(raw_code, "rawValue", 1, true) == nil and string.find(raw_code, "case low", 1, true) ~= nil,
          "a raw-value enum keeps its case and declares no synthesized member")
    check(raw_keys[swift_shard.key_of(init_row)] == true and raw_keys[swift_shard.key_of(raw_value)] == true,
          "the synthesized members of a raw-value enum are rendered keys")
    check(string.find(code, "extension Foundation.URL {", 1, true) ~= nil and string.find(code, "import Foundation", 1, true) ~= nil,
          "a type of another module becomes an extension and its module is imported")
    check(string.find(code, "public class Base", 1, true) ~= nil, "a plain class gets the public access level")
    check(string.find(code, "public final class Box", 1, true) ~= nil, "a final class keeps the public access level")
    check(string.find(code, "public override func describe()", 1, true) ~= nil, "an overriding method carries override")
    check(string.find(code, "public required init()", 1, true) ~= nil, "a required initializer carries required")
    check(string.find(code, "public convenience init()", 1, true) ~= nil, "a convenience initializer carries convenience")
    check(string.find(code, "public actor Worker {", 1, true) ~= nil and string.find(code, "Actor", 1, true) == nil,
          "an actor is declared with its keyword and not with an Actor conformance")
    check(string.find(code, "Opaque", 1, true) == nil and string.find(code, "some ", 1, true) == nil,
          "an opaque typealias is not rendered")

    -- The superclass chain: a class lists only the conformances its chain does not provide, the chain read from the class index (keyed
    -- "Module.Api", as swift_model.class_index keys it). Top conforms to P; Sub is a Top and lists P and Q; Leaf is a Sub and lists P,
    -- Q and R. Sub renders "Fixture.Top, Q" and Leaf "Fixture.Sub, R"; with no index nothing is dropped.
    local function class_row(name, superclass, conformances)
        return {framework = "Fixture", kind = "swift-class", name = name, container = "-", owner_module = "-", attributes = "-",
                is_open = "-", generic_sig = "-", availability = "-", raw = "-", superclass = superclass, conformances = conformances}
    end
    local sub = class_row("Sub", "Fixture.Top", "P,Q")
    local leaf = class_row("Leaf", "Fixture.Sub", "P,Q,R")
    local index = {["Fixture.Top"] = class_row("Top", "-", "P"), ["Fixture.Sub"] = class_row("Sub", "Fixture.Top", "Q")}
    local chained = render.render({sub, leaf}, "Fixture", known, index)
    check(string.find(chained, "public class Sub: Fixture.Top, Q {", 1, true) ~= nil,
          "a class lists its superclass and only the conformances the superclass does not provide")
    check(string.find(chained, "public class Leaf: Fixture.Sub, R {", 1, true) ~= nil,
          "the superclass chain is followed up: a conformance a grandparent gives is not listed")
    local unchained = render.render({sub, leaf}, "Fixture", known)
    check(string.find(unchained, "public class Sub: Fixture.Top, P, Q {", 1, true) ~= nil,
          "without a class index every declared conformance is listed")

    -- A declared name that is a Swift keyword is spelled between backticks; a generic signature's module qualifier is imported.
    local keyword = {framework = "Fixture", kind = "swift-constant", name = "default", container = "-", side = "-", type = "Swift.Int",
                     accessors = "-", overriding = "-", availability = "-", owner_module = "-"}
    check(string.find(render.render({keyword}, "Fixture", known), "public var `default`: Swift.Int", 1, true) ~= nil,
          "a declared name that is a Swift keyword is spelled between backticks")
    keyword.name = "as"
    check(string.find(render.render({keyword}, "Fixture", known), "public var `as`: Swift.Int", 1, true) ~= nil,
          "as, a keyword that is not a declaration word, is spelled between backticks too")
    local bound = class_row("Bound", "-", "-")
    bound.generic_sig = "<T : Other.Thing>"
    check(string.find(render.render({bound}, "Fixture", {Other = true}), "import Other\n", 1, true) ~= nil,
          "a module named in a generic signature is imported")
    local pack = class_row("Pack", "-", "-")
    pack.generic_sig = "<each Input, Output>"
    check(string.find(render.render({pack}, "Fixture", {}), "class Pack<each Input, Output>", 1, true) ~= nil,
          "a parameter pack is spelled with its each keyword in the clause, not as a parameter named each")

    -- An implementation module is imported as its public module: an extension of SwiftUICore's type imports SwiftUI and keeps the
    -- qualifier (the public module re-exports it), a module does not import its own public module, and without the map the
    -- implementation module is imported as before.
    local extended = class_row("Font", "-", "-")
    extended.owner_module = "SwiftUICore"
    local public = {SwiftUICore = "SwiftUI"}
    local listed = {SwiftUI = true, SwiftUICore = true}
    local mapped = render.render({extended}, "Charts", listed, nil, public)
    check(string.find(mapped, "import SwiftUI\n", 1, true) ~= nil and string.find(mapped, "import SwiftUICore", 1, true) == nil,
          "an implementation module is imported as its public module")
    check(string.find(mapped, "extension SwiftUICore.Font {", 1, true) ~= nil,
          "the extension keeps its qualifier: the public module re-exports the implementation module")
    check(string.find(render.render({extended}, "SwiftUI", listed, nil, public), "import SwiftUI\n", 1, true) == nil,
          "a module does not import its own public module")
    check(string.find(render.render({extended}, "Charts", listed), "import SwiftUICore\n", 1, true) ~= nil,
          "without the public map the implementation module is imported")

    -- An extension of another module's type declares no inheritance Swift would reject: a protocol's declares none, and a class's
    -- names its conformances only (the superclass is the class's own declaration).
    local ext_protocol = class_row("View", "-", "Escapable")
    ext_protocol.kind = "swift-protocol"
    ext_protocol.owner_module = "SwiftUICore"
    check(string.find(render.render({ext_protocol}, "Charts", known), "extension SwiftUICore.View {", 1, true) ~= nil,
          "an extension of another module's protocol declares no inheritance")
    local ext_class = class_row("Ext", "UIKit.UIViewController", "NSCoding")
    ext_class.owner_module = "UIKit"
    check(string.find(render.render({ext_class}, "Charts", known), "extension UIKit.Ext: NSCoding {", 1, true) ~= nil,
          "an extension of another module's class lists its conformances, not its superclass")

    -- A declaration the digester gives the error type "_" for has nothing to render from: it is left out (a model gap the round
    -- trip counts), and a typed declaration beside it is still rendered.
    local gap = {framework = "Fixture", kind = "swift-constant", name = "Gap", container = "-", side = "-", type = "_",
                 accessors = "-", overriding = "-", availability = "-", owner_module = "-"}
    local typed_beside = {framework = "Fixture", kind = "swift-constant", name = "Kept", container = "-", side = "-",
                          type = "Swift.Int", accessors = "-", overriding = "-", availability = "-", owner_module = "-"}
    local left_out, left_keys = render.render({gap, typed_beside}, "Fixture", known)
    check(render.untyped(gap) and not render.untyped(typed_beside),
          "a row whose type is the error type is untyped, a typed row is not")
    check(left_keys[swift_shard.key_of(gap)] == nil and left_keys[swift_shard.key_of(typed_beside)] == true,
          "the rendered keys hold the typed row and not the untyped one")
    check(string.find(left_out, "Gap", 1, true) == nil and string.find(left_out, "public var Kept: Swift.Int", 1, true) ~= nil,
          "a declaration the digester gives no type is not rendered; a typed one beside it is")

    -- A superclass argument the digester gives canonically (the Greek tau, then _0_I: the subclass's I-th parameter) is spelled
    -- with the subclass's own parameter name, so the file holds no canonical name; a canonical name the signature does not give
    -- is kept.
    local generic_base = class_row("Sub", "Fixture.Base<\207\132_0_0>", "-")
    generic_base.generic_sig = "<Value>"
    local spelled = render.render({generic_base}, "Fixture", known)
    check(string.find(spelled, "public class Sub<Value>: Fixture.Base<Value> {", 1, true) ~= nil,
          "a superclass argument that is the subclass's first parameter is spelled with its name")
    check(string.find(spelled, "\207\132", 1, true) == nil, "no canonical name is left in the rendered text")

    -- A member's generic parameter is not declared again when its type declares the same name: Swift rejects the shadowing in the
    -- Swift 6 language mode. The member of Record<Output, Failure> takes its container's Output as it is; its own parameter is
    -- declared.
    local record = raw_row("swift-struct", "Record", "-", {generic_sig = "<Output, Failure where Failure : Swift.Error>"})
    local init_row = raw_row("swift-method", "init(record:)", "Record", {params = "Record.Type | [Output]",
                             generic_sig = "<Output, Failure where Failure : Swift.Error>"})
    local own_row = raw_row("swift-method", "fold(_:)", "Record", {type = "Output", params = "[Output]",
                            generic_sig = "<Output, Failure, Mine>"})
    local nested, nested_keys = render.render({record, init_row, own_row}, "Fixture", known)
    check(string.find(nested, "public init(record: [Output])", 1, true) ~= nil,
          "a member does not declare its type's parameter again")
    check(string.find(nested, "init<Output", 1, true) == nil, "no member declares a parameter that shadows its type's")
    check(string.find(nested, "func fold<Mine>(_ p0: [Output]) -> Output", 1, true) ~= nil,
          "a member's own parameter is declared; the type's is not")
    check(nested_keys[swift_shard.key_of(init_row)] == true, "the shadowing member is a rendered key")

    print("swift render test: " .. (failures == 0 and "OK" or ("FAIL " .. failures)))
    if failures > 0 then
        os.exit(1)
    end
end
