-- Writes coremidi-expectations.h from the macOS oracle's recorded output: the lines of oracle/batch.m (one per message:
-- "<tag> in: <words> -> <words>"), recorded as oracle/batch-up.txt and oracle/batch-down.txt.
-- Usage (from this directory): xmake l expectations.lua <batch-up.txt> <batch-down.txt> <out.h>
-- The oracle answers every message of each batch; the header keeps all of the MIDI 1.0 -> 2.0 answers and every
-- 256th of the 2.0 -> 1.0 ones, so the table is small enough to read. The rules themselves are in the library's
-- CharonCoreMIDI.c; this file only records what macOS said.

local function strip(text)
    return (text:gsub("^%s+", ""):gsub("%s+$", ""))
end

local function hexlist(text)
    local values = {}
    for word in text:gmatch("%S+") do
        values[#values + 1] = tonumber(word, 16)
    end
    return values
end

local function rows(path)
    local out = {}
    for raw in io.lines(path) do
        local line = strip(raw)
        if not (line:find("^MISMATCH") or line:find("^cases=")) then
            local tag, inWords, outWords = line:match("^(.-) in: (.-) %-> (.*)$")
            if tag then
                out[#out + 1] = {tag, hexlist(inWords), hexlist(outWords)}
            end
        end
    end
    return out
end

local function words(values)
    local text = {}
    for i, w in ipairs(values) do
        text[i] = string.format("0x%08Xu", w)
    end
    return table.concat(text, ", ")
end

local function emit(name, items, handle)
    handle:write("static const charon_expect " .. name .. "[] = {\n")
    for _, row in ipairs(items) do
        local tag, inWords, outWords = row[1], row[2], row[3]
        handle:write(string.format('    {"%s", {%s}, %d, {%s}, %d},\n', tag, words(inWords), #inWords, words(outWords), #outWords))
    end
    handle:write("};\n")
end

function main(upPath, downPath, outPath)
    local up = rows(upPath)
    local down = {}
    for index, row in ipairs(rows(downPath)) do
        if (index - 1) % 256 == 0 then
            down[#down + 1] = row
        end
    end

    local handle = assert(io.open(outPath, "w"))
    handle:write("// Generated by expectations.lua from the macOS oracle (tests/backports/host/coremidi/oracle/batch.m).\n")
    handle:write("// Do not edit: regenerate. ASCII only.\n")
    handle:write("typedef struct charon_expect {\n    const char *tag;\n    unsigned int in[4];\n    int inCount;\n")
    handle:write("    unsigned int out[8];\n    int outCount;\n} charon_expect;\n\n")
    emit("charon_expect_up", up, handle)
    handle:write("\n")
    emit("charon_expect_down", down, handle)
    handle:close()
    print(string.format("up=%d down=%d", #up, #down))
end
