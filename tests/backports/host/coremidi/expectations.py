#!/usr/bin/env python3
# Writes coremidi-expectations.h from the macOS oracle's recorded output: the lines of
# tests/backports/host/coremidi/oracle/batch.m (one per message: "<tag> in: <words> -> <words>").
# Usage: expectations.py <batch-up.txt> <batch-down.txt> <out.h>
# The oracle answers every message of each batch; the header keeps all of the MIDI 1.0 -> 2.0 answers and every
# 256th of the 2.0 -> 1.0 ones, so the table is small enough to read. The rules themselves are in the library's
# CharonCoreMIDI.c; this file only records what macOS said.
import re
import sys

LINE = re.compile(r'^(.*?) in: (.*?) -> (.*)$')


def rows(path):
    out = []
    for line in open(path):
        line = line.strip()
        if line.startswith('MISMATCH') or line.startswith('cases='):
            continue
        m = LINE.match(line)
        if m:
            out.append((m.group(1), [int(w, 16) for w in m.group(2).split()], [int(w, 16) for w in m.group(3).split()]))
    return out


def emit(name, items, handle):
    handle.write(f'static const charon_expect {name}[] = {{\n')
    for tag, words, out in items:
        handle.write(f'    {{"{tag}", {{{", ".join("0x%08Xu" % w for w in words)}}}, {len(words)}, '
                     f'{{{", ".join("0x%08Xu" % w for w in out)}}}, {len(out)}}},\n')
    handle.write('};\n')


def main():
    up = rows(sys.argv[1])
    down = rows(sys.argv[2])
    down = [row for index, row in enumerate(down) if index % 256 == 0]
    with open(sys.argv[3], 'w') as handle:
        handle.write('// Generated by expectations.py from the macOS oracle (tests/backports/host/coremidi/oracle/batch.m).\n')
        handle.write('// Do not edit: regenerate. ASCII only.\n')
        handle.write('typedef struct charon_expect {\n    const char *tag;\n    unsigned int in[4];\n    int inCount;\n')
        handle.write('    unsigned int out[8];\n    int outCount;\n} charon_expect;\n\n')
        emit('charon_expect_up', [(t, i, o) for t, i, o in up], handle)
        handle.write('\n')
        emit('charon_expect_down', [(t, i, o) for t, i, o in down], handle)
    print(f'up={len(up)} down={len(down)}')


main()
