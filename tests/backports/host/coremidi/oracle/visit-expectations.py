#!/usr/bin/env python3
# Writes ../visit-expectations.h from the recorded visitor output of oracle/visit.m (visit-macos.txt) and of the utility
# probe (visit-jr.txt). Usage: python3 visit-expectations.py <out.h>, run from this directory.
import re
import sys

LABEL = re.compile(r'^(.*?) in: ((?:[0-9A-F]{8} ?)+)$')
JR = re.compile(r'^in ([0-9A-F]{8})$')
BYTES = re.compile(r'bytes=([0-9A-F]+)$')


def parse(path):
    rows = []
    label = None
    words = None
    for raw in open(path):
        line = raw.strip()
        m = LABEL.match(line)
        if m:
            label = m.group(1)
            words = [int(w, 16) for w in m.group(2).split()]
            continue
        m = JR.match(line)
        if m:
            label = 'jr'
            words = [int(m.group(1), 16)]
            continue
        m = BYTES.search(line)
        if m and (line.startswith('ts=') or line.startswith('type=')):
            hexs = m.group(1)
            # visit.m prints all 28 bytes; visit-jr.txt prints the first 16, and the rest is not compared for it.
            values = [int(hexs[i:i + 2], 16) for i in range(0, len(hexs), 2)]
            rows.append((label, words, values + [0] * (28 - len(values))))
    return rows


def main():
    rows = parse('visit-macos.txt') + parse('visit-jr.txt')
    with open(sys.argv[1], 'w') as h:
        h.write('// Generated by oracle/visit-expectations.py from the macOS visitor (oracle/visit.m, visit-jr.txt). Do not edit.\n')
        h.write('typedef struct charon_visit_case {\n    const char *label;\n    unsigned int words[4];\n    int wordCount;\n')
        h.write('    unsigned char bytes[28];\n} charon_visit_case;\n\n')
        h.write('static const charon_visit_case charon_visit_cases[] = {\n')
        for label, words, b in rows:
            padded = words + [0] * (4 - len(words))
            h.write('    {"%s", {%s}, %d, {%s}},\n' % (label, ', '.join('0x%08Xu' % w for w in padded), len(words),
                                                   ', '.join('0x%02X' % x for x in b)))
        h.write('};\n')
    print(f'cases={len(rows)}')


main()
