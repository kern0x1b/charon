#!/usr/bin/env python3
"""Renames the port's 135 VideoToolbox constants, so one host binary carries the port's build and the
host's own side by side and every constant is compared under a name of its own."""
import sys

out = sys.argv[1]
names = [l.strip() for l in open(sys.argv[2]) if l.strip()]
with open(out, "w") as handle:
    handle.write("// Generated by rename.py: the port's constants, under names of their own.\n")
    for name in names:
        handle.write("#define %s Charon%s\n" % (name, name))
