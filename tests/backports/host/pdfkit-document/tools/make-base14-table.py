#!/usr/bin/env python3
"""Generate the standard fourteen's advances, FROM A MEASUREMENT, into a C table.

    make-base14-table.py <host-base14 output> <out.c>

The table in the port is the standard metrics of PDF 1.7 Annex F, and it is generated from a run of
`tools/host-base14.m` over `tools/make-font-fixtures.py`'s base-fourteen fixtures rather than typed by
hand, for the reason the numbers are not in any API: CGFontCreateWithFontName answers 43.2070 for "page 1"
in Courier where the host answers 43.2000, so the only source that answers the host is a measurement of
the host.  Running this tool again against the same run output must reproduce the file byte for byte, and
`--check` says so rather than rewriting it.

WHAT IS MEASURED: every printable ASCII code, 32..126, one fixture per face per half so that no code is
lost to the host's own cut at 83 characters in one show operator, and a third fixture per face whose
whole-line rect gives code 32 - the space is a leading character in the first half and the line rule
trims that, so its width is derived as whole - 2 * w(A) over two numbers already measured.

The unit is THOUSANDTHS OF AN EM, which is what /Widths itself is written in (PDF 1.7 Table 8.27), so a
width enters the geometry as value * size / 1000 with no conversion anywhere else.
"""
import re
import sys

# The fourteen, in the spelling the /BaseFont name uses (PDF 1.7 Table 7.21).  The key is the file stem
# make-font-fixtures.py writes for each, which is the face name lowercased.
FACES = [
    "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
    "Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
    "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
    "Symbol", "ZapfDingbats",
]

FIRST_CODE = 32
LAST_CODE = 126


def read(path):
    """{face: {code: width in thousandths of an em}} out of a host-base14 run."""
    widths, face = {}, None
    for line in open(path):
        if " text-len=" in line:
            match = re.match(r"cgfixture-base14-(.+)-\d\.pdf", line)
            if match is None:
                continue
            # the -space fixture is named <face>-space.pdf and does not match the -<digit> pattern above,
            # so it is read separately below
            face = match.group(1)
            widths.setdefault(face, {})
            continue
        match = re.match(r"\s*(\d+) (.|\S) x=([\d.]+) w=([\d.]+)", line)
        if match is not None and face is not None:
            widths[face][int(match.group(1))] = float(match.group(4)) / 12.0 * 1000.0
    return widths


def read_spaces(path):
    """{face: width of code 32}, from the -space fixtures' whole-line rects and the w(A) beside them."""
    spaces, face = {}, None
    pending = None
    for line in open(path):
        match = re.match(r"cgfixture-base14-(.+)-space\.pdf text-len=(\d+) "
                         r"whole=([\d.-]+),[\d.-]+,([\d.-]+),[\d.-]+", line)
        if match is not None:
            face = match.group(1)
            pending = float(match.group(4))
            continue
        match = re.match(r"\s*65 A x=([\d.-]+) w=([\d.-]+)", line)
        if match is not None and face is not None and pending is not None:
            # whole - w(A) - w(A), the space in the middle.  The FIRST 'A' is enough: both are the same
            # character and the measurement prints it twice.
            spaces[face] = (pending - 2.0 * float(match.group(2))) / 12.0 * 1000.0
            pending = None
    return spaces


def read_descents(path, drawn_at=720.0, size=12.0):
    """{face: descent in thousandths of an em}, from the -descent fixtures.

    The fixture draws "Ag" at y=720 with /F1 12 Tf and NO /FontDescriptor, so the y the host answers IS
    the face's own descent scaled, and the rect's bottom sits that far BELOW the baseline - so the value
    is NEGATIVE and is (y - 720) * 1000 / 12.  Writing it the other way round is the mistake this line is
    here for: it produced +230 for Helvetica, and the reader then answered 722.76 for a line drawn at
    720 where the host answers 717.2402 - the sign, and 5.52pt of it.

    No transcription of a published descent is involved, which matters because one of these is not what
    the specification's table would have said - Courier answers 246 where the AFM says 157 - and the
    measurement is the authority.
    """
    descents = {}
    for line in open(path):
        match = re.match(r"cgfixture-base14-(.+)-descent\.pdf text-len=\d+ "
                         r"whole=[\d.-]+,([\d.-]+),", line)
        if match is not None:
            descents[match.group(1)] = round((float(match.group(2)) - drawn_at) * 1000.0 / size, 4)
    return descents


def emit(widths, spaces, descents):
    out = []
    out.append("// GENERATED by tools/make-base14-table.py from a run of tools/host-base14.m - do not edit.")
    out.append("//")
    out.append("// The standard fourteen's advances, in THOUSANDTHS OF AN EM, which is the unit /Widths is")
    out.append("// written in (PDF 1.7 Table 8.27).  A font with no /Widths - and a document relying on one of")
    out.append("// these fourteen has none - is answered out of here, because the metrics are the FORMAT's own")
    out.append("// data and no API on this release hands them over: CGFontCreateWithFontName answers 43.2070 for")
    out.append("// \"page 1\" in Courier where the host answers 43.2000, measured.")
    out.append("//")
    out.append("// The numbers were MEASURED, one character at a time, over make-font-fixtures.py's base-fourteen")
    out.append("// fixtures; facts/PDFKit/Selection11.md names the run.  Codes 32..126 only: the fixtures draw")
    out.append("// those and no others, so a code outside the span has no width here and the reader below says so")
    out.append("// rather than reaching past the end of the row.")
    out.append("//")
    out.append("// Symbol and ZapfDingbats read ZERO for almost every code, and that is measured rather than a")
    out.append("// gap: their built-in encodings are not WinAnsi, so a code written for another face resolves to no")
    out.append("// glyph in them.  Code 32 is the exception - 250 for Symbol, 278 for ZapfDingbats - because the")
    out.append("// space is the one code that resolves in every one of the fourteen.")
    out.append("")
    out.append("typedef struct {")
    out.append("    const char *name;")
    out.append("    short widths[%d];   // code - 32" % (LAST_CODE - FIRST_CODE + 1))
    out.append("    // THE FACE'S OWN DESCENT, in thousandths of an em and NEGATIVE, which is the other half")
    out.append("    // of Annex F's data this port needs: it is what puts the BOTTOM of a rect, and a document")
    out.append("    // relying on a standard font often carries no /FontDescriptor to read one from.  Measured")
    out.append("    // per face over the -descent fixtures, not transcribed - Courier answers 246 where a")
    out.append("    // published AFM table says 157, so the measurement is what goes in.")
    out.append("    //    A FLOAT and not a short, at the measurement's own precision: Helvetica's is")
    out.append("    //    -229.9833 and not -230, and rounding it to -230 moves every rect built from it by")
    out.append("    //    0.0002pt - which is the difference between 717.2400 and the host's 717.2402 on every")
    out.append("    //    fixture make-object-fixtures.py writes.")
    out.append("    float descent;")
    out.append("} CharonBase14Face;")
    out.append("")
    for face in FACES:
        stem = face.lower()
        row = widths.get(stem, {})
        space = spaces.get(stem)
        if space is None:
            raise SystemExit("%s: no -space fixture in the run output" % face)
        values = []
        for code in range(FIRST_CODE, LAST_CODE + 1):
            if code == FIRST_CODE:
                values.append(int(round(space)))
            elif code in row:
                values.append(int(round(row[code])))
            else:
                raise SystemExit("%s: code %d was not measured" % (face, code))
        if stem not in descents:
            raise SystemExit("%s: no -descent fixture in the run output" % face)
        out.append("static const CharonBase14Face kCharonBase14_%s = { \"%s\", {" % (
            stem.replace("-", "_"), face))
        for i in range(0, len(values), 16):
            out.append("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
        out.append("}, %.4f };" % descents[stem])
        out.append("")
    out.append("static const CharonBase14Face *const kCharonBase14[] = {")
    for face in FACES:
        out.append("    &kCharonBase14_%s," % face.lower().replace("-", "_"))
    out.append("};")
    out.append("")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) not in (3, 4):
        raise SystemExit("usage: make-base14-table.py <host-base14 output> <out.c> [--check]")
    table = emit(read(sys.argv[1]), read_spaces(sys.argv[1]), read_descents(sys.argv[1]))
    if len(sys.argv) == 4 and sys.argv[3] == "--check":
        if open(sys.argv[2]).read() != table:
            print("DIFFER: %s is not what this measurement produces" % sys.argv[2])
            sys.exit(1)
        print("holds: %s is exactly what this measurement produces" % sys.argv[2])
        return
    with open(sys.argv[2], "w") as handle:
        handle.write(table)
    print("wrote %s" % sys.argv[2])


if __name__ == "__main__":
    main()