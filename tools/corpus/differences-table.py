#!/usr/bin/env python3
# differences-table.py CI-DIFF MODELIO-DIFF [--page PATH] [--write]
#
# The two differential runs, read as compare.py wrote them, turned into the group tables
# facts/CoreImage/Differences.md carries.  The tables are generated here and not written by
# hand, because a hand-written count is a number nobody checks: the last pass had a table that
# contradicted its own run in five places and three of the forty-one lines in no row at all.
#
# What it prints per group: the count, the first differing key, and the two lines that key
# produced.  What it refuses to do: a table that does not add up.  The sum of the counts is
# compared with the "N different" the run itself printed, and a difference is an error - so a
# group that loses a key, a group that gains one, and a row that describes a family the run no
# longer has are all caught by the same arithmetic.
#
#   differences-table.py ci-diff.txt modelio-diff.txt
#       prints both tables and the arithmetic, exit 0 only if both add up
#   differences-table.py ci-diff.txt modelio-diff.txt --page <markdown>
#       also reads the page and reports every count in it that this run does not produce
#
# The key of a line is compare.py's key: the text up to the first number, and the n-th
# occurrence of a key is the n-th of that key.  Groups are the key prefixes below, and a key
# that matches no group is a failure of this script rather than a group of its own - a new
# family of differences must be given a name here before the page can say where it belongs.
#
# The page a band reads is not regenerated by this script - it is prose, and the sentences in it
# are the findings - but every COUNT in it is one of the numbers below, and `--page` compares the
# two.  So a count cannot be restated by hand without the check noticing, and a group that gains
# or loses a key is caught by the arithmetic rather than by a reader counting rows.

import argparse
import collections
import re
import sys

# The group a key belongs to, by the first words of the key.  Longest prefix first, so
# "share cylinder" is not swallowed by a rule that would match "cylinder".
CIIMAGE_GROUPS = [
    ("shape", ("shape",)),
    ("repr", ("repr",)),
    ("ctx", ("ctx",)),
    ("imp", ("imp",)),
    ("odd set", ("odd set",)),
    ("alg", ("alg", "premul")),
]
MODELIO_GROUPS = [
    ("cube mesh", ("cube mesh",)),
    ("share cylinder", ("share cylinder",)),
    ("cylinder", ("cylinder vertices", "cylinder min")),
    ("voxrule", ("voxrule",)),
    ("voxels after", ("voxels after",)),
    ("voxel extent", ("voxel extent",)),
    ("voxel indices", ("voxel indices",)),
    ("mesh attributes", ("mesh attributes",)),
    ("mesh min", ("mesh min",)),
    ("tri mesh", ("tri mesh", "tribin mesh")),
    ("stack matrix", ("stack matrix",)),
    ("canImport obj", ("canImport obj",)),
]
KEY = re.compile(r'^(.*?)(-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)(\s|$)')


def family_label(keys):
    """The word a group's keys all start with, as the run spells it.

    The one-sided figures are quoted in prose, and prose spells things its own way - a
    sentence that says "the representation lines" is a true sentence this matcher cannot
    read.  So the label is taken from the run rather than from the page: the longest whole
    word every key of the group begins with.  It is a quotation matcher, and it says so: a
    sentence spelled differently reads as MISSING rather than as agreeing, which is the
    safe direction - a page that stops quoting a figure in the form the run spells it is
    asked for it, and not silently passed over.
    """
    words = [k.split(" ")[0] for k in keys if k.split()]
    if not words:
        return None
    label = words[0]
    for w in words[1:]:
        while label and not w.startswith(label):
            label = label[:-1]
    return label or None


def read_differences(path):
    """Every `different:` line compare.py wrote, as (key, host line, port line), in order."""
    out, host, port = [], None, None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("different: "):
            host = line[len("different: "):]
        elif line.startswith("        the port: "):
            port = line[len("        the port: "):]
            if host is not None:
                m = KEY.match(host)
                out.append((m.group(1) if m else host, host, port))
                host = port = None
    return out


def read_one_sided(path):
    """The one-sided lines, by which side answers, keyed the same way differences are.

    A one-sided line is a measurement the other side does not have: the probe did not ask it,
    or that side answers nothing for it.  It is not a disagreement, and the direction matters -
    "the port has bytes where the system has none" and "the system has bytes where the port
    has none" are opposite facts, and a sentence about one of them must not quote the other's
    count.  That is the one prose number in the differences page that no arithmetic caught, so
    it is counted here and checked by --page.
    """
    out = collections.Counter()
    keys = collections.defaultdict(list)
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        for side, tag in (("only the system answers: ", "system"), ("only the port answers: ", "port")):
            if line.startswith(side):
                key = line[len(side):].split(" ")[0]
                out[tag] += 1
                keys[tag].append(line[len(side):])
    return out, keys


def read_total(path):
    """The `N different` of the run itself, which is what the table has to add up to."""
    for line in open(path, encoding="utf-8"):
        m = re.search(r': (\d+) measurements, (\d+) the same, (\d+) different, (\d+) one side only', line)
        if m:
            return tuple(int(g) for g in m.groups())
    return None


def group_of(key, groups):
    for name, prefixes in groups:
        for prefix in prefixes:
            if key.startswith(prefix):
                return name
    return None


def table(differences, groups, label):
    rows, unattributed = [], []
    for key, host, port in differences:
        name = group_of(key, groups)
        if name is None:
            unattributed.append(key)
        rows.append((name, key, host, port))
    by_group = {}
    for name, key, host, port in rows:
        by_group.setdefault(name, []).append((key, host, port))
    print("### %s: %d groups from %d differences" % (label, len(by_group), len(differences)))
    print()
    print("| group | n | the first key | the system | the port |")
    print("| --- | --- | --- | --- | --- |")
    total = 0
    for name, _ in groups:
        entries = by_group.get(name)
        if not entries:
            print("| `%s` | 0 | - | - | - |" % name)
            continue
        total += len(entries)
        key, host, port = entries[0]
        print("| `%s` | %d | `%s` | %s | %s |" % (name, len(entries), key.strip(),
                                                   host[:70], port[:70]))
    for name in sorted(set(by_group) - set(n for n, _ in groups)):
        print("| `%s` | %d | UNATTRIBUTED - give this key a group in this script | | |" % (name, len(by_group[name])))
    print()
    print("    the table's counts add up to %d" % total)
    if unattributed:
        print("    keys in no group: %d  %s" % (len(unattributed), sorted(set(unattributed))[:5]))
    return total, unattributed


def page_counts(path):
    """Every `| `group` | n |` row of one page, and whether the page has that table at all.

    One path, not a list: `--page` is append-able, so the caller passes one page at a time.
    The `has_table` flag is what keeps the group check off a page that carries no table -
    a facts page about the accumulator is not wrong for not holding the whole run's groups.
    """
    out, has_table = {}, False
    for line in open(path, encoding="utf-8"):
        if re.match(r'\|\s*group\s*\|\s*n\s*\|', line):
            has_table = True
        m = re.match(r'\|\s*`([^`]+)`\s*\|\s*(\d+)\s*\|', line)
        if m:
            out[m.group(1)] = int(m.group(2))
    return out, has_table


def main():
    """Entry point.  A finding is exit 1, a page or a run the tool cannot read is exit 2 with a
    `tool error:` line, and nothing else.

    The distinction is not decoration.  Before this, a page the tool could not read died inside
    argparse-adjacent code and Python exited 1 - the same status as a finding - so a caller that
    checked only the status could not tell a green tool that had found something from a tool that
    had fallen over, and the self-test could not assert either.  Every uncaught error inside the
    tool is now reported as a tool error and exits 2, which is a status nothing else uses.
    """
    try:
        return run()
    except SystemExit:
        raise
    except Exception as error:                     # noqa: BLE001 - and it is re-raised as exit 2
        sys.stderr.write("tool error: %s: %s\n" % (type(error).__name__, error))
        return 2


def run():
    parser = argparse.ArgumentParser()
    parser.add_argument("ci")
    parser.add_argument("modelio")
    # --page may be given more than once; every page that quotes a count is checked
    parser.add_argument("--page", action="append", default=[])
    opts = parser.parse_args()

    failed = False
    for path, groups, label, want in ((opts.ci, CIIMAGE_GROUPS, "CoreImage", 40),
                                      (opts.modelio, MODELIO_GROUPS, "ModelIO", 41)):
        sided, keys = read_one_sided(path)
        print("    one-sided lines in the %s run, by which side answers: system %d, port %d"
              % (label, sided["system"], sided["port"]))
        for tag in ("system", "port"):
            for name, prefixes in groups:
                n = sum(1 for k in keys[tag] if any(k.startswith(p) for p in prefixes))
                if n:
                    print("        one-sided on the %s's side in %r: %d" % (tag, name, n))
        print()
        total, unattributed = table(read_differences(path), groups, label)
        run = read_total(path)
        if run is None:
            print("    FAIL %s: the run printed no verdict line, so there is nothing to add up to" % label)
            failed = True
            continue
        print("    the run says            %d different, %d measurements, %d the same, %d one side only"
              % (run[2], run[0], run[1], run[3]))
        if total != run[2]:
            print("    FAIL %s: the table adds up to %d and the run has %d different" % (label, total, run[2]))
            failed = True
        if total != want:
            print("    FAIL %s: the table adds up to %d and the page claims %d" % (label, total, want))
            failed = True
        if unattributed:
            print("    FAIL %s: %d difference lines are in no group" % (label, len(unattributed)))
            failed = True
        print()

    if opts.page:
        # Every family that has a one-sided line at all, taken from the run and named by the run.
        # There is no literal anywhere below: the old version matched the literal `repr`, and a page
        # that wrote "further repr lines" - the same fact, the same page - was silently passed, which
        # is the opposite of the safe direction its own commit claimed it was.
        keys = read_one_sided(opts.ci)[1]
        families = {}
        for side in ("port", "system"):
            for name, prefixes in CIIMAGE_GROUPS:
                picked = [k for k in keys[side] if any(k.startswith(p) for p in prefixes)]
                if picked:
                    families.setdefault(name, {"port": 0, "system": 0, "label": family_label(picked)})
                    families[name][side] = len(picked)

        for page in opts.page:
            # The page is written with hard wraps, so a sentence about a figure can have a newline
            # in the middle of it; read the text as one line before matching any pattern in it.
            text = re.sub(r"\s+", " ", open(page, encoding="utf-8").read())
            # The group table is read off the file as it stands, line by line, because a table row is
            # a line and collapsing the page would join them.
            written, has_table = page_counts(page)

            # (a) THE GROUP TABLE, on a page that has one, and UNCONDITIONALLY.  It used to sit
            # below a `continue` that fired when the family clauses were not found, so a page that
            # spelled its figures a way the matcher did not read also had its group counts
            # unchecked - and a wrong `shape` count went through as exit 0.  The group counts do not
            # depend on the figures, so nothing about them is conditional on them.
            if has_table:
                for path, groups, which in ((opts.ci, CIIMAGE_GROUPS, "CoreImage"),
                                            (opts.modelio, MODELIO_GROUPS, "ModelIO")):
                    by_group = {}
                    for key, host, port in read_differences(path):
                        by_group.setdefault(group_of(key, groups) or "UNATTRIBUTED", []).append(key)
                    for name, entries in sorted(by_group.items()):
                        if name == "UNATTRIBUTED":
                            continue
                        if name not in written:
                            print("FAIL %s: the page has a group table and no row for %r, which holds %d differences"
                                  % (page, name, len(entries)))
                            failed = True
                        elif written[name] != len(entries):
                            print("FAIL %s: the page says %r is %d and the run has %d"
                                  % (page, name, written[name], len(entries)))
                            failed = True

            # (b) THE FIGURES, per family, and the label is matched with or without backticks -
            # both spellings are the same sentence and the page may use either.
            for name, figures in sorted(families.items()):
                label = figures["label"]
                # The run's bare key, quoted the way the page quotes it or not: `repr` and repr are
                # the same sentence and either may be written.  The alternation is non-capturing, so
                # the groups are the figure and the side - and getting that wrong is an IndexError
                # rather than a wrong number, which is what it was the first time.
                pattern = (r"(\d+) further (?:`" + re.escape(label) + r"`|" + re.escape(label) +
                           r") lines (?:are )?(one-sided on the [a-z]+'s side)")
                clauses = {}
                for m in re.finditer(pattern, text):
                    clauses[m.start()] = (int(m.group(1)), m.group(2))
                for at, (said, what) in sorted(clauses.items()):
                    want = figures["port"] if "port" in what else figures["system"]
                    if said != want:
                        print("FAIL %s: a clause says %d %s lines are %s and the run has %d"
                              % (page, said, label, what, want))
                        failed = True
                # The two clauses of a pair have to be together.  The prose writes the pair as two
                # clauses joined by "and", so a clause with no partner within WINDOW characters of it
                # is half the fact - which is what the sentence that said 30 was.
                WINDOW = 240
                for at, (said, what) in sorted(clauses.items()):
                    partner = "one-sided on the system's side" if "port" in what else "one-sided on the port's side"
                    lo, hi = (at, at + WINDOW) if "port" in what else (max(0, at - WINDOW), at)
                    if not any(w == partner and lo <= p < hi for p, (_, w) in clauses.items()):
                        print("FAIL %s: a clause states %d %s lines %s with no clause for the other side within %d characters of it: that is half the fact"
                              % (page, said, label, what, WINDOW))
                        failed = True
                # (c) A page that carries the group table and the run has one-sided lines in a family
                # that family the page does NOT state is a finding, not a pass.  A page with the table
                # is the page that claims to account for the run, so a family it leaves out is a gap in
                # that claim - and the old code turned the same situation into a silent `continue`.
                if has_table and not clauses and (figures["port"] or figures["system"]):
                    print("FAIL %s: the page has the group table and the run has %d and %d one-sided `%s` lines, and the page states no figure for them: a page that accounts for the run has to account for this"
                          % (page, figures["port"], figures["system"], label))
                    failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
