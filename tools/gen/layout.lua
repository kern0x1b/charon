local VERSION = "2"

local LAYOUT = {
    VERSION = VERSION,
    SDK_ID = "sdk-26.2-headers",
    SOURCES_ROOT = "packages/a/apple-backports",
    SNAP_ROOT = "packages/a/apple-backports/spec",
    OUT_ROOT = "packages/a/apple-backports/.gen",
    PINS_ROOT = "packages/a/apple-backports/overrides/hashes",
    REGISTRY = "packages/a/apple-backports/registry",
    MARK = "// GENERATED by tools/gen.py version " .. VERSION .. ". Do not edit. Regenerate: see tools/gen.py.",
    SPEC_COLUMNS = {"kind", "api", "cls", "key", "introduced", "decl", "availability", "hash", "value_status", "value",
                    "host_value", "value_source", "owned", "tbd", "shape", "measured"},
    PIN_COLUMNS = {"api", "key", "pinned", "pinned-by", "registry"},
}

-- The constants of the layout: the version of the generator's output, the snapshot's identifiers and folders, the column lists.
function constants()
    return LAYOUT
end

-- The committed snapshot of a framework: spec, members record, manifest, protocols, functions, and the classification.
function snap_dir(tree, fw)
    return path.join(tree, LAYOUT.SNAP_ROOT, fw)
end

-- The build directory of a framework: what the generator emits. Gitignored, never committed.
function gen_dir(tree, fw)
    return path.join(tree, LAYOUT.OUT_ROOT, fw)
end

function spec_path(tree, fw)
    return path.join(snap_dir(tree, fw), "spec." .. LAYOUT.SDK_ID .. ".tsv")
end

function pins_path(tree, fw)
    return path.join(tree, LAYOUT.PINS_ROOT, fw .. ".tsv")
end

function manifest_path(tree, fw)
    return path.join(snap_dir(tree, fw), "manifest.tsv")
end

function members_path(tree, fw)
    return path.join(snap_dir(tree, fw), "members.tsv")
end

-- The registry rows of a framework: registry/<F>/*.json, as paths relative to the tree (the form pins and reports name them).
function registry_dir(fw)
    return path.join(LAYOUT.REGISTRY, fw)
end
