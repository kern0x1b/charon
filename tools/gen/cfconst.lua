-- The measured constants of the 31 objects: the NSString and CFString and number constants that the committed objects carried before this
-- table, each read out of a held dyld cache. The table is tools/corpus/cfconst.tsv (one row per declaration: its object, the headers the
-- object imports, the release and architecture of the cache its value was read from, the declared type, the name and the initializer), and
-- its facts are tools/corpus/cfconst.md beside it. Each object is written by gen into .gen/<Framework>/<Object>.m, so the build produces
-- the sources and nothing of them is committed.
--
-- It is measured.lua's writer for the rows that were committed before. The objects' rows are the same declarations, written in the same
-- order (sorted by name) with the same spacing; what is not kept is the prose, which is the facts file's. check (tools/corpus/cfconst-check.lua)
-- reads each row's value out of its named cache and reports any row the cache does not hold.

local order = import("order", {anonymous = true})
local files = import("files", {anonymous = true})

local TABLE = "tools/corpus/cfconst.tsv"
local FACTS = "tools/corpus/cfconst.md"
-- The frameworks the table names. A tree that has none of them (a fixture) reads no table, as measured.lua's SOURCES does.
local FRAMEWORKS = {Contacts = true, CoreData = true, CoreServices = true, Foundation = true, HealthKit = true, IOSurface = true, UIKit = true}

-- The table's rows as records keyed by its header. A field is one tab-separated text: the table holds no quotes and no tabs in a field,
-- which the header check below relies on, and a missing trailing field reads as "".
local function records(text)
    local lines = {}
    for line in string.gmatch(text, "[^\n]+") do
        table.insert(lines, line)
    end
    local header = nil
    local out = {}
    for _, line in ipairs(lines) do
        local fields = {}
        for field in string.gmatch(line .. "\t", "([^\t]*)\t") do
            table.insert(fields, field)
        end
        if header == nil then
            header = fields
        else
            assert(#fields == #header, "the cfconst table row has " .. #fields .. " fields, its header " .. #header .. ": " .. line)
            local record = {}
            for k, key in ipairs(header) do
                record[key] = fields[k]
            end
            table.insert(out, record)
        end
    end
    assert(header ~= nil, "the cfconst table is empty")
    return out
end

local cached = nil

-- The rows of the table, read once per run.
local function rows(tree)
    if cached == nil then
        local text = files.read_text(path.join(tree, TABLE))
        assert(text ~= nil, "the measured constants table is missing: " .. TABLE)
        cached = records(text)
    end
    return cached
end

-- The header comment of an object: what the object is, the release and cache its values come from, and where the facts are.
local function header_lines(record)
    return {
        "// The measured constants of " .. record.object .. " (" .. FACTS .. ").",
        "//",
        "// Generated:  xmake l tools/gen.lua gen --framework " .. record.framework,
        "// from " .. TABLE .. ". Do not edit this file by hand; regenerate it.",
        "//",
        "// The values below were read out of the dyld shared cache of iOS " .. record.cache .. " (the facts file has the reading),",
        "// except a struct the reader does not read, which the facts file also explains. tools/corpus/cfconst-check.lua reads each",
        "// value back out of that cache.",
    }
end

-- The object's text: its header comment, its imports, then its declarations sorted by name.
local function object_text(object_rows)
    local first = object_rows[1]
    local lines = header_lines(first)
    table.insert(lines, "")
    for header in string.gmatch(first.headers, "[^|]+") do
        table.insert(lines, "#import " .. header)
    end
    table.insert(lines, "")
    local sorted = table.move(object_rows, 1, #object_rows, 1, {})
    table.sort(sorted, function(a, b)
        return order.less(a.name, b.name)
    end)
    for _, row in ipairs(sorted) do
        local line = row.declaration .. " " .. row.name .. " = " .. row.initializer .. ";"
        if row.comment ~= "" then
            line = line .. "   " .. row.comment
        end
        table.insert(lines, line)
    end
    table.insert(lines, "")
    return table.concat(lines, "\n")
end

-- The table's rows, for the cross-check (tools/corpus/cfconst-check.lua), which reads each one back out of its cache.
function table_rows(tree)
    return rows(tree)
end

-- The objects of a framework that the table defines: name -> text, each name a file of .gen/<F>/. Empty for a framework the table does not
-- name.
function objects(tree, fw)
    local by_object, names = {}, {}
    if not FRAMEWORKS[fw] then
        return {}
    end
    for _, record in ipairs(rows(tree)) do
        if record.framework == fw then
            if by_object[record.object] == nil then
                by_object[record.object] = {}
                table.insert(names, record.object)
            end
            table.insert(by_object[record.object], record)
        end
    end
    local out = {}
    for _, name in ipairs(names) do
        out[name .. ".m"] = object_text(by_object[name])
    end
    return out
end
