#!/usr/bin/env python3
"""The single code generator of apple-backports: one entry, sub-generators for each class of row.

    gen.py input  --tree T --framework F --ledger L --sdk S [--owned FILE]   build the spec table from the 26.2 SDK
    gen.py pin    --tree T --framework F [--repin KEY]                       record override pins in the sidecar
    gen.py gen    --tree T --framework F                                     write gen/F/ and the reports
    gen.py check  --tree T --framework F                                     regenerate in memory, compare, report
    gen.py trace  --tree T --framework F --class C                           write the trace-only defaults of class C
    gen.py diff   --tree T --framework F                                     host differential of the constants

SPEC (owner, 2026-10-09; design: coordination/wave-2026-10-03/design-spec-driven.md). The firmware plays the role of the
swagger file. The spec of a framework is one table, gen/<F>/spec.sdk-26.2-headers.tsv, built by `input` from the 26.2 SDK
headers (every constant, property and method of the framework's classes) and from the ledger's missing constants with their
values read from the macOS framework of this host (tools/gen-objc-constants-oracle.m). A new SDK or a new cache is a new
table (a new input-id), not a change to this file.

LAYERS (gen/<F>/ is generated, committed, deterministic, never edited by hand):
  1. CONTRACT, always built and shipped: spec.h holds a declaration hash per spec member (CHARON_SPEC_HASH_<key>); the
     constants of the framework are defined in <F>Constants<NN>.m, one object per release they arrived in.
  2. DEFAULTS, trace builds only, never shipped: trace/<F>Defaults.m stubs each member without an override, logs
     `unimplemented: <member>` once, returns the documented zero. Guarded by CHARON_TRACE_DEFAULTS.
  3. VERIFICATION, always built: verify.c asserts, per override, that the hash it was written against equals the spec hash
     (CHARON_IMPLEMENTS). A changed declaration fails the build naming the member.

OVERRIDES (never touched): the existing hand-written source and registry rows of a framework. A registry row present for a
member is an override; the generator skips it. The hash an override was written against lives in the sidecar
overrides/hashes/<F>.tsv (api, key, pinned, pinned-by, registry), not in the registry. `pin` writes a pin only for an
override with no pin yet (bootstrap, marked pinned-by=bootstrap for review); `pin --repin KEY` re-pins one key by hand.

RULES: gen/ is never edited by hand; `check` fails on any drift of gen/ from what this file emits, on a stale pin, and on a
pin the input table no longer holds is reported as removed (warned, not failed). Regeneration is idempotent and byte stable
(sorted output, ASCII, no timestamps). Nothing here deletes a row or a file of a person.

GENERATED FILES list, per framework: spec.sdk-26.2-headers.tsv (input), spec.h, <F>Constants<NN>.m, verify.c, new.tsv,
stale.tsv, removed.tsv, README.md, and trace/<F>Defaults.m when `trace` was run.
"""

