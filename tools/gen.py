def probe(tree, fw, names):
    run = os.path.join(tree, ".agent-work", "runs", "gen", fw)
    os.makedirs(run, exist_ok=True)
    binary = os.path.join(run, "oracle")
    subprocess.run(["clang", "-fobjc-arc", "-w", "-framework", "Foundation",
                    os.path.join(tree, "tools", "gen-objc-constants-oracle.m"), "-o", binary], check=True)
    library = os.path.join(HOST, fw + ".framework", fw)
    values = {}
    for name in names:
        one = os.path.join(run, "name.txt")
        write(one, name + "\n")
        result = subprocess.run([binary, library, one], capture_output=True, text=True)
        if result.returncode != 0:
            values[name] = ("probe-crashed", "-")
            continue
        for line in result.stdout.splitlines():
            found, status, cls, value = line.split("\t")
            values[found] = (status, value)
    return values


def objc_escape(text):
    """The text as the body of an ObjC string literal, ASCII only, escaped the way tools/gen-objc-constants-oracle.m escapes it."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif 0x20 <= ord(ch) < 0x7f:
            out.append(ch)
        else:
            out.append("\\u%04X" % ord(ch) if ord(ch) < 0x10000 else "?")
    return "".join(out)


def ios_constants(path):
    """symbol -> the string the iOS 26.2 cache holds for it (cfstring kind), from v-cache26's constants table."""
    csv.field_size_limit(10 ** 8)
    values, conflicts = {}, set()
    if not os.path.exists(path) and os.path.exists(path + ".gz"):
        path = path + ".gz"
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt", newline="", encoding="ascii", errors="replace") as handle:
        # QUOTE_NONE: the table holds quote characters inside values, and the default quoting drops such rows
        for row in csv.DictReader(handle, delimiter="\t", quoting=csv.QUOTE_NONE):
            if row["value_kind"] != "cfstring":
                continue
            name = row["symbol"][1:] if row["symbol"].startswith("_") else row["symbol"]
            if name in values and values[name] != row["value"]:
                conflicts.add(name)
            values.setdefault(name, row["value"])
    return values, conflicts


def measured_releases(path):
    """symbol -> first release the held caches export it in, from the gate's release-split output (object, symbol, release).

    A symbol the held caches do not export is `none`; a summary line (MIXED-RELEASES) is not a symbol and is skipped.
    """
    out = {}
    for line in read_any(path).splitlines():
        cols = line.split("\t")
        if len(cols) == 3 and cols[1].startswith("_") and cols[1] != "MIXED-RELEASES":
            out[cols[1][1:]] = cols[2]
    return out


def registry_constants(tree, fw):
    """name -> registry file, for every constant the framework's registry rows name (any status)."""
    out = {}
    for path in sorted(glob.glob(os.path.join(tree, REGISTRY, fw, "*.json")) + glob.glob(os.path.join(tree, REGISTRY, fw + ".json"))):
        with open(path) as handle:
            data = json.load(handle)
        for entry in data.get("entries", data if isinstance(data, list) else []):
            if entry.get("kind") == "constant":
                out.setdefault(entry["api"], os.path.relpath(path, tree))
    return out


def cmd_input(args):
    fw = args.framework
    typedefs = string_typedefs(args.sdk, fw)
    rows = []
    owned = {}
    if args.owned:
        for line in read_any(args.owned).splitlines():
            if line.strip():
                name, branch = line.split("\t")
                owned[name] = branch
    with open(os.path.join(args.ledger, fw + ".tsv"), newline="") as handle:
        ledger = [r for r in csv.DictReader(handle, delimiter="\t") if r["status"] == "missing"
                  and r["kind"] == "constant" and r["lang"] == "objc" and r["needs"] == "code+lift"]
    decls = constant_decls(args.sdk, fw, [r["api"] for r in ledger], typedefs)
    undeclared = [r["api"] for r in ledger if r["api"] not in decls]
    if undeclared and fw != "Foundation":
        # Foundation declares NSCalendarIdentifier and friends; a CoreFoundation row the ledger lists may be one of them
        decls.update(constant_decls(args.sdk, "Foundation", undeclared, typedefs))
    # A name the registry already holds, in any status (implemented, absent, ...), is a decision a person took: the generator
    # leaves it alone, so it is not generated and not read by the oracle.
    for name, path in registry_constants(args.tree, fw).items():
        owned.setdefault(name, "registry:" + path)
    strings = [r["api"] for r in ledger if r["api"] not in owned and r["api"] in decls
               and object_shape(decls[r["api"]][0], typedefs) == "string"]
    values = probe(args.tree, fw, strings) if strings else {}
    symbols, classes = tbd_exports(args.sdk, fw)
    if fw != "Foundation":
        foundation_symbols, _ = tbd_exports(args.sdk, "Foundation")
        symbols = symbols | foundation_symbols
    cf = cf_typedefs(args.sdk, fw)
    measured = measured_releases(args.measured) if args.measured else {}
    ios_path = args.ios_constants or IOS_CONSTANTS
    if not (os.path.exists(ios_path) or os.path.exists(ios_path + ".gz")):
        raise SystemExit("no iOS 26.2 constants table at %s (.gz)" % ios_path)
    ios, ios_conflicts = ios_constants(ios_path)
    ios_sha = hashlib.sha256(open(ios_path if os.path.exists(ios_path) else ios_path + ".gz", "rb").read()).hexdigest()[:16]
    differences = []
    if args.measured:
        keep = [(api, rel) for api, rel in sorted(measured.items())]
        write(os.path.join(snap_dir(args.tree, fw), "measured.held-caches.tsv"),
              "symbol\trelease\n" + "".join("%s\t%s\n" % (api, rel) for api, rel in keep))
    for r in ledger:
        decl, avail = decls.get(r["api"], ("", ""))
        if r["api"] in owned:
            status, value = "owned:" + owned[r["api"]], "-"
        elif not decl:
            status, value = "undeclared", "-"
        elif object_shape(decl, typedefs) != "string":
            status, value = "numeric", "-"
        else:
            status, value = values[r["api"]]
        host_value, source = value, "host-macos"
        if status == "found" and r["api"] in ios:
            value, source = objc_escape(ios[r["api"]]), "ios-26.2-cache"
            if value != host_value:
                differences.append((r["api"], host_value, value))
        elif status != "found" and r["api"] not in owned and r["api"] in ios and decl and object_shape(decl, typedefs) == "string":
            # The host does not carry the framework (AddressBookUI is iOS-only), so no host value exists: the iOS cache is the
            # only oracle, and it is the expectation.
            status, value, host_value, source = "found", objc_escape(ios[r["api"]]), "-", "ios-26.2-cache (no host value)"
        if status != "found":
            value = "-"
            host_value = "-"
        rows.append({"kind": "constant", "api": r["api"], "cls": "-", "key": mangle(r["api"]),
                     "introduced": r["introduced"], "decl": decl or "-", "availability": avail or "-",
                     "hash": digest("constant", r["api"], decl, avail), "value_status": status, "value": value,
                     "host_value": host_value, "value_source": source,
                     "owned": owned.get(r["api"], "-"),
                     "tbd": "exported" if r["api"] in symbols else "not-exported",
                     "shape": "cf" if constant_base(decl) in cf | {"CFStringRef"} else "ns",
                     "measured": measured.get(r["api"], "-"),
                     "source": "macOS %s framework, dlsym (tools/gen-objc-constants-oracle.m)" % fw})
    seen = set()
    for cls, kind, api, alias, decl, avail in members_of(header_text(args.sdk, fw)):
        if api in seen:
            continue
        seen.add(api)
        key = mangle(api)
        rows.append({"kind": kind, "api": api, "cls": cls, "key": key, "introduced": "-", "decl": decl,
                     "availability": avail or "-", "hash": digest(kind, api, decl, avail or "-"),
                     "value_status": "-", "value": "-", "host_value": "-", "value_source": "-", "owned": "-",
                     "tbd": "class-exported" if cls in classes else "class-not-exported", "shape": "-", "measured": "-",
                     "source": "26.2 SDK header of %s" % fw})
    keys = [r["key"] for r in rows]
    dup = sorted(set(k for k in keys if keys.count(k) > 1))
    if dup:
        raise SystemExit("key collision in the spec: " + ", ".join(dup[:10]))
    path = spec_path(args.tree, fw)
    lines = ["\t".join(SPEC_COLUMNS)]
    for r in rows:
        lines.append("\t".join(str(r[c]) for c in SPEC_COLUMNS))
    write(path, "\n".join(lines) + "\n")
    counts = {}
    for r in rows:
        counts[r["kind"]] = counts.get(r["kind"], 0) + 1
    print("spec %s: %s" % (os.path.relpath(path, args.tree), ", ".join("%s %d" % (k, counts[k]) for k in sorted(counts))))
    write(os.path.join(snap_dir(args.tree, fw), "value-differences.tsv"),
          "api\thost_macos\tios_26_2\n" + "".join("%s\t%s\t%s\n" % d for d in sorted(differences)))
    print("values: %d constants read from the iOS 26.2 cache (table sha256 %s), %d differ from macOS (iOS wins); %d cache symbols with conflicting values"
          % (sum(1 for r in rows if r["value_source"].startswith("ios")), ios_sha, len(differences), len(ios_conflicts)))
    return 0


# ---------------------------------------------------------------- spec, overrides, pins

def load_spec(tree, fw):
    with open(spec_path(tree, fw), newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def load_overrides(tree, fw):
    """Hand-written registry rows of the framework that are implemented: api -> (registry file, entry)."""
    found = {}
    for path in sorted(glob.glob(os.path.join(tree, REGISTRY, fw, "*.json"))):
        with open(path) as handle:
            data = json.load(handle)
        for entry in data["entries"]:
            if entry.get("status") == "implemented" and entry.get("kind") in ("method", "property", "class"):
                if entry.get("owner", "").startswith("generator:"):
                    continue
                found.setdefault(entry["api"], (os.path.relpath(path, tree), entry))
    return found


def spec_index(rows):
    """Every spec row under its own api and, for a property, under the dotted name the registry uses (Class.name)."""
    index = {}
    for r in rows:
        index.setdefault(r["api"], r)
        if r["kind"] == "property":
            name = r["api"].rstrip("]").split()[-1]
            index.setdefault("%s.%s" % (r["cls"], name), r)
    return index


def load_pins(tree, fw):
    path = pins_path(tree, fw)
    if not os.path.exists(path):
        return []
    with open(path, newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def write_pins(tree, fw, pins):
    cols = ["api", "key", "pinned", "pinned-by", "registry"]
    lines = ["\t".join(cols)] + ["\t".join(p[c] for c in cols) for p in sorted(pins, key=lambda p: p["key"])]
    write(pins_path(tree, fw), "\n".join(lines) + "\n")


def cmd_pin(args):
    fw = args.framework
    spec = load_spec(args.tree, fw)
    index = spec_index(spec)
    pins = load_pins(args.tree, fw)
    by_key = {p["key"]: p for p in pins}
    added = 0
    for api, (registry, entry) in load_overrides(args.tree, fw).items():
        target = index.get(api)
        if target is None:
            continue
        key = target["key"]
        if key not in by_key:
            pin = {"api": api, "key": key, "pinned": target["hash"], "pinned-by": "bootstrap", "registry": registry}
            pins.append(pin)
            by_key[key] = pin
            added += 1
        elif args.repin == key:
            by_key[key]["pinned"] = target["hash"]
            by_key[key]["pinned-by"] = "repin"
    write_pins(args.tree, fw, pins)
    print("pins %s: %d total, %d added" % (fw, len(pins), added))
    return 0


# ---------------------------------------------------------------- generated outputs (pure: text in, text out)

def render(tree, fw):
    spec = load_spec(tree, fw)
    index = spec_index(spec)
    pins = load_pins(tree, fw)
    overrides = load_overrides(tree, fw)
    files = {}
    head = "// Framework: %s. Spec: %s.\n" % (fw, SDK_ID)
    lines = [MARK, head.rstrip("\n"), "#ifndef CHARON_%s_SPEC_H" % fw.upper(), "#define CHARON_%s_SPEC_H" % fw.upper()]
    for r in spec:
        lines.append("#define CHARON_SPEC_HASH_%s 0x%sULL" % (r["key"], r["hash"]))
    lines.append("#endif")
    files["spec.h"] = "\n".join(lines) + "\n"
    constants = [r for r in spec if r["kind"] == "constant" and r["value_status"] == "found" and r["owned"] == "-"
                 and r["tbd"] == "exported"]
    by_release = {}
    for r in constants:
        by_release.setdefault(release_of(r), []).append(r)
    for release in sorted(by_release, key=release_key):
        body = [MARK, "#import <%s/%s.h>" % (fw, fw), ""]
        for r in by_release[release]:
            body.append(constant_definition(r))
        files["%sConstants%s.m" % (fw, release.replace(".", ""))] = "\n".join(body) + "\n"
    verify = [MARK, '#include "spec.h"', "#define CHARON_IMPLEMENTS(key, pinned, name) \\",
              '  _Static_assert(CHARON_SPEC_HASH_##key == (pinned), name " was written against another declaration: the 26.2 spec changed, review the override and re-pin it")']
    stale, removed = [], []
    pinned_keys = set()
    for p in sorted(pins, key=lambda p: p["key"]):
        pinned_keys.add(p["key"])
        target = next((r for r in spec if r["key"] == p["key"]), None)
        if target is None:
            removed.append((p["api"], "pin without a spec member: the override stays, reported", p["registry"]))
            continue
        if target["hash"] != p["pinned"]:
            stale.append((p["api"], p["key"], p["pinned"], target["hash"], p["registry"]))
        verify.append('CHARON_IMPLEMENTS(%s, 0x%sULL, "%s");' % (p["key"], p["pinned"], p["api"]))
    for api, (registry, entry) in sorted(overrides.items()):
        if api not in index and entry.get("kind") != "class" and not api.startswith("-["):
            removed.append((api, "registry override the 26.2 spec does not hold", registry))
    files["verify.c"] = "\n".join(verify) + "\n"
    new = []
    for r in spec:
        if r["kind"] in ("method", "property") and r["key"] not in pinned_keys and r["api"] not in overrides:
            new.append((r["cls"], r["kind"], r["api"], r["hash"]))
    files["new.tsv"] = "\n".join(["class\tkind\tapi\thash"] + ["\t".join(x) for x in new]) + "\n"
    files["stale.tsv"] = "\n".join(["api\tkey\tpinned\tspec\tregistry"] + ["\t".join(x) for x in stale]) + "\n"
    files["removed.tsv"] = "\n".join(["api\treason\tregistry"] + ["\t".join(x) for x in removed]) + "\n"
    files["README.md"] = readme(fw, spec, pins, stale, removed, new, by_release)
    # The per-row index the registry check reads (registry() in modules/apple/backports.lua): the fields of a registry row.
    # Paths are relative to the package root, where registry/ and gen/ both live.
    index = ["framework\tkind\tapi\tintroduced\tminimum\tmaximum\tstatus\teffect\tfacts\tsource\towner\tdeclhash"]
    for release in sorted(by_release, key=release_key):
        source = ".gen/%s/%sConstants%s.m" % (fw, fw, release.replace(".", ""))
        for r in by_release[release]:
            index.append("\t".join([fw, "constant", r["api"], release, "6.0", release, "implemented", "",
                                     ".gen/%s/README.md" % fw, source, "generated", r["hash"]]))
    files["rows.tsv"] = "\n".join(index) + "\n"
    return files


def release_of(r):
    """The release a constant is placed and registered at: the first release the held caches export it in (measured),
    else the header's introduced release where no held cache exports it (`none`)."""
    measured = r.get("measured", "-")
    return measured if measured not in ("-", "none", "") else r["introduced"]


def constant_base(decl):
    words = [w for w in re.findall(r"[A-Za-z_]\w*", decl) if w not in ("const", "volatile")]
    return words[0] if words else "NSString"


def constant_definition(r):
    """The definition of one constant, in the canonical type of its shape: the variable is const where the header's is.

    A typedef of NSString (PKPaymentNetwork, AVAudioSessionOrientation) defines as NSString *, which is the same type to the
    compiler and needs no SDK typedef that a build SDK may lack; a CFStringRef typedef (SecKeyAlgorithm) defines as CFStringRef
    through a bridging cast from the literal.
    """
    const = re.search(r"\bconst\b", r["decl"]) is not None
    literal = '@"%s"' % r["value"]
    if r.get("shape") == "cf":
        return "%sCFStringRef %s = (__bridge CFStringRef)%s;" % ("const " if const else "", r["api"], literal)
    return "%s %s = %s;" % ("NSString *const" if const else "NSString *", r["api"], literal)


def readme(fw, spec, pins, stale, removed, new, by_release):
    counts = {}
    for r in spec:
        counts[r["kind"]] = counts.get(r["kind"], 0) + 1
    constants = sum(len(v) for v in by_release.values())
    out = [
        "<!-- GENERATED by tools/gen.py version %s. Do not edit. -->" % VERSION,
        "# gen/%s" % fw,
        "",
        "Spec: `spec.%s.tsv` (%s). Contract layer: `spec.h` (one hash per member), %d constant definitions in %d objects"
        " (%s), `verify.c` (one assertion per pinned override)." % (SDK_ID, ", ".join("%s %d" % (k, counts[k]) for k in sorted(counts)),
                                                                   constants, len(by_release), ", ".join(sorted(by_release, key=release_key))),
        "Overrides: %d pins in `overrides/hashes/%s.tsv`; stale %d; removed %d; members without an override %d (new.tsv)."
        % (len(pins), fw, len(stale), len(removed), len(new)),
        "",
        "Rules: gen/ is never edited by hand; `tools/gen.py check` fails on any drift from what the generator emits and on a"
        " stale pin; a removed override is reported, never deleted.",
        "",
        "## Sources (the SOURCES table of tools/gen.py)",
        "",
        "| source | kind | licence | loader | status | adds |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    out += ["| " + " | ".join(row) + " |" for row in SOURCES]
    out += ["", "## Open-source leads (licence and use, owner rule 2026-10-09)", "",
            "| lead | library | licence | use | status |", "| --- | --- | --- | --- | --- |"]
    out += ["| " + " | ".join(row) + " |" for row in OSS_LEADS]
    out += ["", "## References", "",
            "Libraries read as a reference for behaviour while writing a row, and the files consulted. None for this framework: the"
            " constants' values come from the macOS framework of this host and their declarations from the 26.2 headers.", ""]
    return "\n".join(out)


def stale_constants(base, fw, files):
    """Constants objects a previous generation wrote and this one no longer emits (a regrouping by measured release)."""
    return sorted(os.path.basename(p) for p in glob.glob(os.path.join(base, fw + "Constants*.m"))
                  if os.path.basename(p) not in files)


def frameworks_with_snapshot(tree):
    return sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(tree, SNAP_ROOT, "*", "spec.%s.tsv" % SDK_ID)))


def manifest_path(tree, fw):
    return os.path.join(snap_dir(tree, fw), "manifest.tsv")


def members_path(tree, fw):
    return os.path.join(snap_dir(tree, fw), "members.tsv")


def spec_hash(r):
    """The declaration hash of a spec row. A method or property is hashed from its declaration and availability as they are
    now, so a hand edit of the declaration moves the hash; a constant keeps the hash input recorded (its value is a separate row)."""
    if r["kind"] in ("method", "property"):
        return digest(r["kind"], r["api"], r["decl"], r["availability"] if r["availability"] != "-" else "-")
    return r["hash"]


def read_members(tree, fw):
    path = members_path(tree, fw)
    if not os.path.exists(path):
        return None
    out = {}
    for line in read(path).splitlines()[1:]:
        if line:
            api, digest_text = line.split("\t")
            out[api] = digest_text
    return out


def member_changes(tree, fw):
    """(changed, new, removed): members whose declaration hash differs from the recorded one, members with no record, and
    recorded members the spec no longer holds. None when no record is committed yet."""
    recorded = read_members(tree, fw)
    if recorded is None:
        return None
    current = {r["api"]: spec_hash(r) for r in load_spec(tree, fw)}
    changed = [(api, recorded[api], current[api]) for api in sorted(set(current) & set(recorded)) if current[api] != recorded[api]]
    new = sorted(set(current) - set(recorded))
    removed = sorted(set(recorded) - set(current))
    return changed, new, removed


def read_manifest(tree, fw):
    """file -> sha256 of the text the generator emits, as recorded in the snapshot; None when no manifest is committed yet."""
    path = manifest_path(tree, fw)
    if not os.path.exists(path):
        return None
    out = {}
    for line in read(path).splitlines()[1:]:
        if line:
            name, digest = line.split("\t")
            out[name] = digest
    return out


def digest_of(text):
    return hashlib.sha256(text.encode("ascii")).hexdigest()


def cmd_gen(args):
    """Write the generator's output into the build directory (gen_dir), for one framework or every snapshot with --all.
    --record also writes the manifest of digests into the snapshot: the committed record that `check` compares against."""
    targets = frameworks_with_snapshot(args.tree) if args.all else [args.framework]
    for fw in targets:
        files = render(args.tree, fw)
        base = gen_dir(args.tree, fw)
        for name in stale_constants(base, fw, files):
            os.remove(os.path.join(base, name))
        for name, text in sorted(files.items()):
            write(os.path.join(base, name), text)
        changes = member_changes(args.tree, fw)
        if changes and changes[0] and not args.record:
            for api, old, new in changes[0]:
                print("CHANGED %s: declaration hash %s -> %s (review the override or the stub, then gen --record)" % (api, old, new))
            print("gen %s: refused, %d member declaration(s) changed since the record" % (fw, len(changes[0])))
            return 1
        if args.record:
            lines = ["file\tsha256"] + ["%s\t%s" % (name, digest_of(text)) for name, text in sorted(files.items())]
            write(manifest_path(args.tree, fw), "\n".join(lines) + "\n")
            spec = load_spec(args.tree, fw)
            write(members_path(args.tree, fw), "\n".join(["api\thash"] + ["%s\t%s" % (r["api"], spec_hash(r)) for r in spec
                                                                       if r["kind"] in ("method", "property", "constant")]) + "\n")
        print("gen %s: %d files in %s%s" % (fw, len(files), os.path.relpath(base, args.tree), " (manifest recorded)" if args.record else ""))
    return 0


def constant_names(tree, fw):
    """The constants the generator defines: found in the oracle, not owned by a live branch, exported by 26.2."""
    return [r["api"] for r in load_spec(tree, fw) if r["kind"] == "constant" and r["value_status"] == "found"
            and r["owned"] == "-" and r["tbd"] == "exported"]


def hand_source_of(tree, fw, name):
    """The hand-written source of the framework that defines the name, if any: the generated layer never overlaps one."""
    for path in sorted(glob.glob(os.path.join(tree, SOURCES_ROOT, fw, "*.[mh]"))):
        if re.search(r"^\s*(?:extern\s+)?[\w\s\*]*\b%s\s*=" % re.escape(name), read_any(path), re.M):
            return os.path.relpath(path, tree)
    return None


def cmd_check(args):
    """Regenerate in memory from the snapshot and compare with the committed manifest of digests and with the build directory.
    A drift, a stale override pin, or a manifest that does not match the generator fails the check."""
    targets = frameworks_with_snapshot(args.tree) if args.all else [args.framework]
    failed = 0
    for fw in targets:
        files = render(args.tree, fw)
        base = gen_dir(args.tree, fw)
        problems, warnings = [], []
        manifest = read_manifest(args.tree, fw)
        if manifest is None:
            problems.append("no manifest committed in the snapshot: run gen --record")
        else:
            for name, text in sorted(files.items()):
                if manifest.get(name) != digest_of(text):
                    problems.append("snapshot manifest differs from what the generator emits: %s" % name)
            for name in sorted(set(manifest) - set(files)):
                problems.append("manifest names a file the generator no longer emits: %s" % name)
        for name, text in sorted(files.items()):
            path = os.path.join(base, name)
            if not os.path.exists(path):
                warnings.append("not in the build directory yet: %s (run gen)" % name)
            elif read(path) != text:
                problems.append("build directory differs from the generator: %s" % name)
        for name in stale_constants(base, fw, files):
            problems.append("build directory holds a constants object the generator no longer emits: %s" % name)
        changes = member_changes(args.tree, fw)
        if changes is None:
            problems.append("no member record committed: run gen --record")
        else:
            for api, old, new in changes[0]:
                problems.append("member %s changed: declaration hash %s (recorded) -> %s (now)" % (api, old, new))
            for api in changes[1]:
                warnings.append("member with no record yet: %s" % api)
            for api in changes[2]:
                warnings.append("recorded member the spec no longer holds: %s" % api)
        spec = load_spec(args.tree, fw)
        defined = set(re.findall(r"CHARON_SPEC_HASH_(\w+)", files["spec.h"]))
        for r in spec:
            if r["key"] not in defined:
                problems.append("spec member without a hash define: %s" % r["api"])
        stale = [l for l in files["stale.tsv"].splitlines()[1:] if l]
        removed = [l for l in files["removed.tsv"].splitlines()[1:] if l]
        new = [l for l in files["new.tsv"].splitlines()[1:] if l]
        for line in stale:
            problems.append("stale pin: " + line.replace("\t", "  "))
        for line in removed:
            warnings.append("removed override: " + line.replace("\t", "  "))
        for line in problems:
            print("CHECK %s: %s" % (fw, line))
        for line in warnings:
            print("WARN %s: %s" % (fw, line))
        print("check %s: drift and stale %d, removed (warned) %d, members without an override (new) %d"
              % (fw, len(problems), len(removed), len(new)))
        failed += 1 if problems else 0
    return 1 if failed else 0


# ---------------------------------------------------------------- trace layer: generated-but-unimplemented members

# The trace layer is the DEFAULTS of the design: a stub for every declared member of a framework that has no override and no
# hand implementation, compiled only with CHARON_TRACE_DEFAULTS. A stub logs `unimplemented: <framework> <selector>` once per
# member, then returns the zero of its return type (nil for an object, 0 for a scalar or enum, a zeroed struct), and sets the
# NSError an `NSError **` parameter names to an error in the framework's own domain. Block parameters are not invoked.
SCALAR_TYPES = {"BOOL", "bool", "char", "unsigned char", "short", "unsigned short", "int", "unsigned", "unsigned int", "long",
                "unsigned long", "long long", "unsigned long long", "float", "double", "NSInteger", "NSUInteger", "CGFloat",
                "NSTimeInterval", "size_t", "int8_t", "int16_t", "int32_t", "int64_t", "uint8_t", "uint16_t", "uint32_t", "uint64_t"}
TYPE_INDEX_FRAMEWORKS = ("Foundation", "CoreFoundation", "CoreAudio", "CoreAudioTypes", "AudioToolbox", "AudioUnit", "CoreMedia",
                         "CoreGraphics", "CoreMIDI", "CoreVideo")


def strip_platform_blocks(text):
    """The text the iOS build sees: #if TARGET_OS_VISION (and its #else-less forms) blocks are removed, nested ones included."""
    out, depth = [], 0
    for line in text.split("\n"):
        stripped = line.strip()
        if depth == 0 and re.match(r"#\s*if\s+TARGET_OS_VISION\b", stripped):
            depth = 1
            continue
        if depth > 0:
            if re.match(r"#\s*if", stripped):
                depth += 1
            elif re.match(r"#\s*endif", stripped):
                depth -= 1
            continue
        out.append(line)
    return "\n".join(out)


def declared_names(sdk, fw):
    """Every typedef, class and protocol name the iOS build sees in the framework and the frameworks its types come from."""
    names = set()
    for f in (fw,) + TYPE_INDEX_FRAMEWORKS + ("AVFAudio",):
        for path in glob.glob(os.path.join(sdk, "System", "Library", "Frameworks", f + ".framework", "Headers", "*.h")):
            text = strip_platform_blocks(re.sub(r"//[^\n]*", " ", re.sub(r"/\*.*?\*/", " ", read_any(path), flags=re.S)))
            names.update(re.findall(r"typedef\s[^;]*?\b(\w+)\s*(?:NS_\w+|API_\w+|OS_\w+|CF_\w+)?[^;]*;", text))
            names.update(re.findall(r"@(?:interface|protocol)\s+(\w+)", text))
            names.update(re.findall(r"typedef\s+(?:NS_ENUM|NS_OPTIONS|NS_TYPED_ENUM|NS_TYPED_EXTENSIBLE_ENUM|CF_ENUM|enum)[^;]*?\b(\w+)\s*;", text, re.S))
    return names


def type_index(sdk, fw):
    """typedef name -> the text it is defined as, from the framework and the frameworks its types come from."""
    index = {}
    for f in (fw,) + TYPE_INDEX_FRAMEWORKS:
        for path in glob.glob(os.path.join(sdk, "System", "Library", "Frameworks", f + ".framework", "Headers", "*.h")):
            # comments first: a doc comment that mentions `typedef` would otherwise start a match that runs into the real one
            text = re.sub(r"/\*.*?\*/", " ", read_any(path), flags=re.S)
            text = strip_platform_blocks(re.sub(r"//[^\n]*", " ", text))
            for match in re.finditer(r"typedef\s+([^;{}]*?)\s*\b(\w+)\s*(?:API_\w+\([^;]*?\)\s*)*;", text):
                index.setdefault(match.group(2), " ".join(match.group(1).split()))
            for match in re.finditer(r"typedef\s+(?:struct|enum)\b[^{;]*\{[^}]*\}\s*(\w+)\s*;", text, re.S):
                index.setdefault(match.group(1), "struct")
    return index


NULLABILITY_WORDS = re.compile(r"\b(_Nullable|_Nonnull|__nullable|__nonnull|_Null_unspecified|nullable|nonnull|null_resettable|null_unspecified)\b")


PLATFORM_MACROS = re.compile(r"\b__[A-Z][A-Z0-9_]*(?:\([^()]*\))?")


def strip_nullability(decl):
    """A declaration without its nullability words and the platform macros the SDK puts after it (__TVOS_PROHIBITED and the
    like): the stub compiles whether or not the header's audit and availability macros are in scope."""
    return " ".join(PLATFORM_MACROS.sub(" ", NULLABILITY_WORDS.sub(" ", decl)).split())


def resolve_kind(type_text, index, depth=0):
    """'void', 'object', 'scalar' or 'struct' for a declared type, through its typedefs."""
    text = " ".join(type_text.replace("*", " * ").split())
    if text in ("void",):
        return "void"
    if "*" in text or text in ("id", "instancetype") or re.search(r"<.*>", text):
        return "object"
    name = text.split()[-1] if text.split() else text
    if text in SCALAR_TYPES or name in SCALAR_TYPES:
        return "scalar"
    if name in index and depth < 6:
        target = index[name]
        if target == "struct" or target.startswith("struct"):
            return "struct"
        kind = resolve_kind(target, index, depth + 1)
        return kind
    if re.match(r"^(NS_ENUM|NS_OPTIONS|enum)\b", text) or name.startswith("NS") and name.endswith("Options"):
        return "scalar"
    return "struct"


def hand_implementations(tree):
    """(class, selector) for every method a hand-written source of the package defines, and (class, name) for every
    @synthesize or @dynamic, so no stub replaces a hand implementation. A signature spans lines until its brace."""
    found = set()
    root = os.path.join(tree, SOURCES_ROOT)
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in (".gen", "spec", "registry", "facts", "overrides", "gen")]
        for name in filenames:
            if not name.endswith((".m", ".mm")):
                continue
            current, signature = None, None
            for line in read_any(os.path.join(dirpath, name)).splitlines():
                if signature is not None:
                    signature += " " + line.strip()
                    if "{" in line or ";" in line:
                        sel = selector_of(signature.split("{")[0].split(";")[0])
                        if sel:
                            found.add((current, sel))
                        signature = None
                    continue
                impl = re.match(r"^\s*@implementation\s+(\w+)", line)
                if impl:
                    current = impl.group(1)
                    continue
                if re.match(r"^\s*@end\b", line):
                    current = None
                    continue
                if current is None:
                    continue
                synth = re.match(r"^\s*@(?:synthesize|dynamic)\s+(\w+)", line)
                if synth:
                    found.add((current, synth.group(1)))
                if re.match(r"^\s*[-+]\s*\(", line):
                    if "{" in line or ";" in line:
                        sel = selector_of(line.split("{")[0].split(";")[0])
                        if sel:
                            found.add((current, sel))
                    else:
                        signature = line.strip()
    return found


UNDECLARED_CHECK = re.compile(r"\b([A-Z][A-Za-z0-9_]*)\b")
BUILTIN_TYPES = {"BOOL", "NSInteger", "NSUInteger", "CGFloat", "NSTimeInterval", "NSError", "NSString", "NSNumber", "NSArray",
                 "NSDictionary", "NSSet", "NSData", "NSURL", "NSDate", "NSUUID", "NSLocale", "NSMapTable", "NSPointerArray",
                 "NSMeasurement", "NSIndexPath", "NSProgress", "NSOperationQueue", "NSNotificationName", "NSNotificationCenter",
                 "NSOrderedSet", "NSCountedSet", "NSFileHandle", "NSBundle", "NSLayoutConstraint", "NSRange", "UInt32", "SInt32",
                 "OSStatus", "Float32", "Float64", "Boolean", "AudioObjectID", "AudioStreamBasicDescription", "AudioBufferList",
                 "AudioChannelLayout", "AudioComponentDescription", "AudioUnit", "AudioBuffer", "AudioUnitParameterID",
                 "AudioUnitParameterValue", "AudioTimeStamp", "CFStringRef", "CFTypeRef", "CFURLRef", "CMTime", "CGPoint", "CGSize",
                 "CGRect", "CFTimeInterval", "MIDIEndpointRef", "MIDIClientRef"}


def stub_members(spec, fw, sdk, overridden, hand):
    """The stubs for one framework, one per member it does not implement, grouped by class; and the members left out with the reason."""
    index = type_index(sdk, fw)
    declared = declared_names(sdk, fw)
    seen = set()
    by_class, skipped = {}, []
    for r in spec:
        if r["kind"] not in ("method", "property"):
            continue
        cls = r["cls"]
        decl = r["decl"].rstrip(";").strip()
        undeclared = sorted(set(t for t in UNDECLARED_CHECK.findall(strip_nullability(decl))
                                if t not in declared and t not in BUILTIN_TYPES and not t.startswith(("NS_", "API_", "CF_"))))
        if undeclared:
            skipped.append((r["api"], "type not declared for iOS: " + ",".join(undeclared)))
            continue
        if r["kind"] == "property":
            name = r["api"].rstrip("]").split()[-1]
            selector = getter_of(decl, name)
            if r["api"] in overridden or (cls, name) in hand or (cls, selector) in hand:
                skipped.append((r["api"], "override or hand implementation"))
                continue
            decl = strip_nullability(decl)
            type_text = property_type_text(decl, name)
            kind = resolve_kind(type_text, index)
            readwrite = "readonly" not in decl
            if (cls, selector) in seen:
                skipped.append((r["api"], "same selector declared twice in the class"))
                continue
            seen.add((cls, selector))
            by_class.setdefault(cls, []).append(("-[%s %s]" % (cls, selector), "property-get", name, type_text, kind, decl))
            if readwrite and (cls, "set" + name[:1].upper() + name[1:] + ":") not in hand:
                setter = "set%s%s:" % (name[:1].upper(), name[1:])
                by_class[cls].append(("-[%s %s]" % (cls, setter), "property-set", name, type_text, "void", decl))
            continue
        selector = r["api"].rstrip("]").split(" ", 1)[1]
        if r["api"] in overridden or (cls, selector) in hand:
            skipped.append((r["api"], "override or hand implementation"))
            continue
        decl = strip_nullability(decl)
        ret = re.match(r"^[-+]\s*\(\s*([^)]*?)\s*\)", decl)
        if not ret:
            skipped.append((r["api"], "no return type parsed"))
            continue
        if (cls, selector) in seen:
            skipped.append((r["api"], "same selector declared twice in the class"))
            continue
        seen.add((cls, selector))
        kind = resolve_kind(ret.group(1), index)
        by_class.setdefault(cls, []).append((r["api"], "method", selector, ret.group(1), kind, decl))
    return by_class, skipped


def property_type_text(decl, name):
    text = re.sub(r"\([^()]*\)", " ", decl.replace("@property", " "))
    text = re.sub(r"\b(_Nullable|_Nonnull|__nullable|__nonnull|_Null_unspecified|nullable|nonnull|null_resettable)\b", " ", text)
    text = " ".join(text.rstrip(";").split())
    return " ".join(text[:text.rfind(name)].split()) if name in text else text


def stub_text(fw, cls, api, kind, selector, type_text, zero_kind, decl):
    log = ('static BOOL charon_logged = NO; if (!charon_logged) { charon_logged = YES; '
           'fprintf(stderr, "unimplemented: %s %%s\\n", "%s"); }' % (fw, api))
    error_arg = re.search(r"\(\s*NSError\s*\*\s*\*\s*\)\s*(\w+)", decl)
    error = ""
    if error_arg:
        error = ('if (%s) { *%s = [NSError errorWithDomain:@"%s.Unimplemented" code:-1 userInfo:@{NSLocalizedDescriptionKey: '
                 '@"%s is not implemented by the port"}]; } ' % (error_arg.group(1), error_arg.group(1), fw, api))
    if zero_kind == "void":
        zero = ""
    elif zero_kind == "object":
        zero = " return nil;"
    elif zero_kind == "scalar":
        zero = " return 0;"
    else:
        zero = " return (%s){0};" % type_text
    if kind == "property-get":
        head = "- (%s)%s" % (type_text, selector)
    elif kind == "property-set":
        head = "- (void)%s:(%s)value" % (selector[:-1], type_text)
    else:
        head = decl
    return "%s { %s%s%s }" % (head, log, (" " + error) if error else " ", zero.strip())


def cmd_trace(args):
    fw = args.framework
    sdk = args.sdk or SDK26
    spec = load_spec(args.tree, fw)
    overridden = set(load_overrides(args.tree, fw))
    hand = hand_implementations(args.tree)
    by_class, skipped = stub_members(spec, fw, sdk, overridden, hand)
    lines = [MARK, "// Trace-only defaults: built only when CHARON_TRACE_DEFAULTS is set; never shipped. One class per category.",
             "// A stub logs once `unimplemented: %s <selector>`, returns the zero of its type, and sets an NSError an NSError ** names." % fw,
             "// Block parameters are not invoked. Members with an override or a hand implementation are not stubbed.",
             "#ifdef CHARON_TRACE_DEFAULTS", "#import <%s/%s.h>" % (fw, fw), "#include <stdio.h>", ""]
    stubbed = 0
    for cls in sorted(by_class):
        members = by_class[cls]
        lines.append("@interface %s (CharonTrace)" % cls)
        for api, kind, selector, type_text, zero_kind, decl in members:
            if kind == "property-get":
                lines.append("- (%s)%s;" % (type_text, selector))
            elif kind == "property-set":
                lines.append("- (void)%s:(%s)value;" % (selector[:-1], type_text))
            else:
                lines.append(decl.rstrip(";") + ";")
        lines.append("@end")
        lines.append("@implementation %s (CharonTrace)" % cls)
        for api, kind, selector, type_text, zero_kind, decl in members:
            if zero_kind == "struct" and type_text.strip() == "":
                skipped.append((api, "no type text"))
                continue
            lines.append(stub_text(fw, cls, api, kind, selector, type_text, zero_kind, decl))
            stubbed += 1
        lines.append("@end")
    lines += ["#endif"]
    path = os.path.join(gen_dir(args.tree, fw), "trace", "%sDefaults.m" % fw)
    write(path, "\n".join(lines) + "\n")
    write(os.path.join(gen_dir(args.tree, fw), "trace", "skipped.tsv"), "api\treason\n" + "".join("%s\t%s\n" % s for s in skipped))
    print("trace %s: %d stubs in %d classes, %d members left out (skipped.tsv)" % (fw, stubbed, len(by_class), len(skipped)))
    return 0


def getter_of(decl, name):
    found = re.search(r"getter\s*=\s*(\w+)", decl)
    return found.group(1) if found else name


def cmd_diff(args):
    fw = args.framework
    if not os.path.isdir(os.path.join(HOST, fw + ".framework")):
        print("differential %s: not on macOS, so no host differential; the iOS 26.2 cache is the only expectation" % fw)
        return 0
    spec = load_spec(args.tree, fw)
    names = [r["api"] for r in spec if r["kind"] == "constant" and r["value_status"] == "found" and r["owned"] == "-"
             and r["tbd"] == "exported"]
    shape = {r["api"]: r["shape"] for r in spec}
    ios_value = {r["api"]: r["value"] for r in spec if r["value_source"] == "ios-26.2-cache"}
    run = os.path.join(args.tree, ".agent-work", "runs", "gen-diff", fw)
    os.makedirs(run, exist_ok=True)
    src = os.path.join(run, "reference.m")
    ref = os.path.join(run, "reference")
    absent = []
    while True:
        body = ["#import <Foundation/Foundation.h>", "#import <stdio.h>"]
        # The reference declares each name with the type macOS declares it with, so the header and the reference agree.
        body += [("extern const CFStringRef %s;" if shape[n] == "cf" else "extern NSString *const %s;") % n for n in names]
        body += ["int main(void) {", "@autoreleasepool {"]
        body += ['printf("%s\\t%%s\\n", [%s UTF8String]);' % (n, ("(__bridge NSString *)" if shape[n] == "cf" else "") + n)
                 for n in names]
        body += ["}", "return 0;", "}"]
        write(src, "\n".join(body) + "\n")
        built = subprocess.run(["clang", "-fobjc-arc", "-w", "-framework", "Foundation", "-framework", fw, src, "-o", ref],
                               capture_output=True, text=True)
        if built.returncode == 0:
            break
        # A name macOS does not export cannot be read on the host: it is named, not compared, and the link is retried.
        missing = set(re.findall(r'"_(\w+)", referenced from', built.stderr))
        if not missing or not missing & set(names):
            print("reference does not link against macOS %s: %s" % (fw, built.stderr.strip()[-200:]))
            return 1
        absent += sorted(missing & set(names))
        names = [n for n in names if n not in missing]
    for n in absent:
        print("NOT ON MACOS %s: not compared" % n)
    reference = dict(l.split("\t", 1) for l in subprocess.run([ref], capture_output=True, text=True).stdout.splitlines())
    sources = sorted(glob.glob(os.path.join(gen_dir(args.tree, fw), fw + "Constants*.m")))
    if not sources or not names:
        print("differential %s: no constant objects to compare" % fw)
        return 0

    dylib = os.path.join(run, "lib%sConstants.dylib" % fw)
    built = subprocess.run(["clang", "-dynamiclib", "-fobjc-arc", "-w", "-framework", "Foundation", "-o", dylib] + sources,
                           capture_output=True, text=True)
    if built.returncode != 0:
        print("gen sources do not build as a host dylib: " + built.stderr.strip()[-300:])
        return 1
    probe_bin = os.path.join(args.tree, ".agent-work", "runs", "gen", fw, "oracle")
    port = {}
    one = os.path.join(run, "one.txt")
    for n in names:
        write(one, n + "\n")
        for line in subprocess.run([probe_bin, dylib, one], capture_output=True, text=True).stdout.splitlines():
            found, status, cls, value = line.split("\t")
            port[found] = (status, value)
    equal, differ, ios_wins = 0, [], 0
    for n in names:
        status, value = port.get(n, ("missing", None))
        ref_value = reference.get(n)
        if status != "found" or ref_value is None:
            differ.append((n, "port %s, reference %s" % (status, "present" if ref_value is not None else "missing")))
        elif value == ref_value.rstrip("\n"):
            equal += 1
        elif n in ios_value and value == ios_value[n]:
            # The iOS 26.2 cache is the expectation (iOS wins): a macOS value the port does not carry is expected, and listed.
            ios_wins += 1
        else:
            differ.append((n, "port %r, reference %r" % (value, ref_value)))
    for n, why in differ:
        print("DIFFERS %s: %s" % (n, why))
    print("differential %s: %d names, %d equal to macOS, %d equal to the iOS 26.2 cache where macOS differs (iOS wins), %d differ, %d not on macOS"
          % (fw, len(names), equal, ios_wins, len(differ), len(absent)))
    return 1 if differ else 0


