def constant_names(tree, fw):
    """The constants the generator defines: found in the oracle, not owned by a live branch, exported by 26.2."""
    return [r["api"] for r in load_spec(tree, fw) if r["kind"] == "constant" and r["value_status"] == "found"
            and r["owned"] == "-" and r["tbd"] == "exported"]


def hand_source_of(tree, fw, name):
    """The hand-written source of the framework that defines the name, if any: the generated layer never overlaps one."""
    for path in sorted(glob.glob(os.path.join(tree, SOURCES_ROOT, fw, "*.[mh]"))):
        if re.search(r"^\s*(?:extern\s+)?[\w\s\*]*\b%s\s*=" % re.escape(name), read_any(path), re.M):
            return os.path.relpath(path, tree)
    return None


def cmd_check(args):
    fw = args.framework
    files = render(args.tree, fw)
    base = gen_dir(args.tree, fw)
    problems, warnings = [], []
    for name, text in sorted(files.items()):
        path = os.path.join(base, name)
        committed = read(path) if os.path.exists(path) else None
        if committed != text:
            problems.append("drift: gen/%s/%s differs from what the generator emits" % (fw, name))
    committed_defines = set(re.findall(r"CHARON_SPEC_HASH_(\w+)", read(os.path.join(base, "spec.h")))) if os.path.exists(os.path.join(base, "spec.h")) else set()
    spec = load_spec(args.tree, fw)
    for r in spec:
        if r["key"] not in committed_defines:
            problems.append("spec member without a hash define: %s" % r["api"])
    for name in constant_names(args.tree, fw):
        hand = hand_source_of(args.tree, fw, name)
        if hand:
            problems.append("generated constant also defined by hand in %s: %s" % (hand, name))
    stale = [l for l in files["stale.tsv"].splitlines()[1:] if l]
    removed = [l for l in files["removed.tsv"].splitlines()[1:] if l]
    new = [l for l in files["new.tsv"].splitlines()[1:] if l]
    for line in stale:
        problems.append("stale pin: " + line.replace("\t", "  "))
    for line in removed:
        warnings.append("removed override: " + line.replace("\t", "  "))
    for line in problems:
        print("CHECK " + line)
    for line in warnings:
        print("WARN " + line)
    print("check %s: drift and stale %d, removed (warned) %d, members without an override (new) %d"
          % (fw, len(problems), len(removed), len(new)))
    return 1 if problems else 0


SCALARS = {"BOOL", "int", "unsigned", "NSInteger", "NSUInteger", "long", "unsigned long", "CGFloat", "float", "double",
           "NSTimeInterval", "uint32_t", "int32_t", "uint64_t", "int64_t", "char", "unsigned char", "short", "UInt32", "SInt32",
           "Float32", "Float64"}


def stub_for(r):
    """A default for one member: the documented zero, logged once. None when the return type is not classified here."""
    decl = r["decl"].rstrip(";").strip()
    if r["kind"] == "property":
        name = r["api"].rstrip("]").split()[-1]
        type_text = re.sub(r"\([^()]*\)", " ", decl.replace("@property", " ")).strip()
        rtype = " ".join(type_text[:type_text.rfind(name)].split())
        signature = "- (%s)%s" % (rtype, name)
        selector = "-[%s %s]" % (r["cls"], name)
    else:
        m = re.match(r"^([-+])\s*\(\s*([^)]*?)\s*\)", decl)
        if not m:
            return None
        rtype = m.group(2)
        signature = decl
        selector = r["api"]
    if rtype == "void":
        zero = ""
    elif "*" in rtype or rtype in ("id", "instancetype") or rtype.startswith("NS") or rtype.startswith("AV"):
        zero = " return nil;"
    elif rtype in SCALARS:
        zero = " return 0;"
    else:
        return None
    body = ('{ static BOOL logged = NO; if (!logged) { logged = YES; fprintf(stderr, "unimplemented: %%s\\n", "%s"); }%s }'
            % (selector, zero))
    return "%s %s" % (signature, body)


def cmd_trace(args):
    fw, cls = args.framework, args.cls
    spec = load_spec(args.tree, fw)
    overridden = set(load_overrides(args.tree, fw))
    members = [r for r in spec if r["cls"] == cls and r["kind"] in ("method", "property") and r["api"] not in overridden]
    stubs, skipped = [], []
    for r in members:
        stub = stub_for(r)
        if stub is None:
            skipped.append(r["api"])
        else:
            stubs.append(stub)
    lines = [MARK, "// Trace-only defaults: built only when CHARON_TRACE_DEFAULTS is set; never shipped.",
             "#ifdef CHARON_TRACE_DEFAULTS", "#import <%s/%s.h>" % (fw, fw), "#include <stdio.h>", "",
             "@interface %s (CharonTrace)" % cls]
    lines += [s.split(" {")[0] + ";" for s in stubs]
    lines += ["@end", "@implementation %s (CharonTrace)" % cls]
    lines += stubs
    lines += ["@end", "#endif"]
    path = os.path.join(gen_dir(args.tree, fw), "trace", "%sDefaults.m" % fw)
    write(path, "\n".join(lines) + "\n")
    write(os.path.join(gen_dir(args.tree, fw), "trace", "skipped.tsv"), "api\n" + "\n".join(skipped) + "\n")
    print("trace %s %s: %d stubs, %d not classified (skipped.tsv)" % (fw, cls, len(stubs), len(skipped)))
    return 0


def cmd_diff(args):
    fw = args.framework
    spec = load_spec(args.tree, fw)
    names = [r["api"] for r in spec if r["kind"] == "constant" and r["value_status"] == "found" and r["owned"] == "-"
             and r["tbd"] == "exported"]
    shape = {r["api"]: r["shape"] for r in spec}
    run = os.path.join(args.tree, ".agent-work", "runs", "gen-diff", fw)
    os.makedirs(run, exist_ok=True)
    src = os.path.join(run, "reference.m")
    ref = os.path.join(run, "reference")
    absent = []
    while True:
        body = ["#import <Foundation/Foundation.h>", "#import <stdio.h>"]
        # The reference declares each name with the type macOS declares it with, so the header and the reference agree.
        body += [("extern const CFStringRef %s;" if shape[n] == "cf" else "extern NSString *const %s;") % n for n in names]
        body += ["int main(void) {", "@autoreleasepool {"]
        body += ['printf("%s\\t%%s\\n", [%s UTF8String]);' % (n, ("(__bridge NSString *)" if shape[n] == "cf" else "") + n)
                 for n in names]
        body += ["}", "return 0;", "}"]
        write(src, "\n".join(body) + "\n")
        built = subprocess.run(["clang", "-fobjc-arc", "-w", "-framework", "Foundation", "-framework", fw, src, "-o", ref],
                               capture_output=True, text=True)
        if built.returncode == 0:
            break
        # A name macOS does not export cannot be read on the host: it is named, not compared, and the link is retried.
        missing = set(re.findall(r'"_(\w+)", referenced from', built.stderr))
        if not missing or not missing & set(names):
            print("reference does not link against macOS %s: %s" % (fw, built.stderr.strip()[-200:]))
            return 1
        absent += sorted(missing & set(names))
        names = [n for n in names if n not in missing]
    for n in absent:
        print("NOT ON MACOS %s: not compared" % n)
    reference = dict(l.split("\t", 1) for l in subprocess.run([ref], capture_output=True, text=True).stdout.splitlines())
    sources = sorted(glob.glob(os.path.join(gen_dir(args.tree, fw), fw + "Constants*.m")))
    dylib = os.path.join(run, "lib%sConstants.dylib" % fw)
    built = subprocess.run(["clang", "-dynamiclib", "-fobjc-arc", "-w", "-framework", "Foundation", "-o", dylib] + sources,
                           capture_output=True, text=True)
    if built.returncode != 0:
        print("gen sources do not build as a host dylib: " + built.stderr.strip()[-300:])
        return 1
    probe_bin = os.path.join(args.tree, ".agent-work", "runs", "gen", fw, "oracle")
    port = {}
    one = os.path.join(run, "one.txt")
    for n in names:
        write(one, n + "\n")
        for line in subprocess.run([probe_bin, dylib, one], capture_output=True, text=True).stdout.splitlines():
            found, status, cls, value = line.split("\t")
            port[found] = (status, value)
    equal, differ = 0, []
    for n in names:
        status, value = port.get(n, ("missing", None))
        ref_value = reference.get(n)
        if status != "found" or ref_value is None:
            differ.append((n, "port %s, reference %s" % (status, "present" if ref_value is not None else "missing")))
        elif value == ref_value.rstrip("\n"):
            equal += 1
        else:
            differ.append((n, "port %r, reference %r" % (value, ref_value)))
    for n, why in differ:
        print("DIFFERS %s: %s" % (n, why))
    print("differential %s: %d names, %d equal, %d differ, %d not on macOS" % (fw, len(names), equal, len(differ), len(absent)))
    return 1 if differ else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["input", "pin", "gen", "check", "trace", "diff", "sources"])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--framework", required=True)
    parser.add_argument("--ledger")
    parser.add_argument("--sdk")
    parser.add_argument("--owned")
    parser.add_argument("--repin")
    parser.add_argument("--class", dest="cls")
    args = parser.parse_args()
    if args.command == "sources":
        return cmd_sources(args)
    if args.command == "input":
        if not (args.ledger and args.sdk):
            raise SystemExit("input needs --ledger and --sdk")
        return cmd_input(args)
    if args.command == "pin":
        return cmd_pin(args)
    if args.command == "gen":
        return cmd_gen(args)
    if args.command == "check":
        return cmd_check(args)
    if args.command == "trace":
        if not args.cls:
            raise SystemExit("trace needs --class")
        return cmd_trace(args)
    return cmd_diff(args)


if __name__ == "__main__":
    sys.exit(main())
